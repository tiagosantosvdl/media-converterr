def command_main(args: argparse.Namespace) -> int:
    if args.command == "hook":
        event_id = capture_hook_event(args.database, args.instance, os.environ)
        if event_id is None:
            print("media_converterr hook test successful")
        else:
            print(f"Queued hook event {event_id}")
        return 0

    if args.command == "systemd" and args.systemd_command == "remove":
        removed = remove_systemd()
        print(f"Removed {len(removed)} systemd unit(s); configuration and data preserved")
        return 0

    settings = load_settings(os.path.abspath(args.config))

    if args.command == "systemd":
        if not os.path.isfile(args.config):
            raise ConfigurationError(
                f"Create the host configuration before installing systemd: {args.config}"
            )
        identity = install_systemd(
            settings,
            args.config,
            args.scan_interval,
            args.user,
            args.group,
            args.allow_root,
        )
        print(f"Installed systemd units as {identity.user}:{identity.group}")
        for warning in validate_service_access(settings, identity):
            print(f"WARNING: {warning}", file=sys.stderr)
        return 0

    created = initialize_database(settings)
    if args.command == "init":
        action = "Created" if created else "Already initialized"
        print(f"{action}: {settings.database_path}")
        print(f"Source database left unchanged: {settings.source_database_path}")
        return 0

    logger = setup_logging(settings, args.verbose)
    conn = connect_database(settings.database_path)
    try:
        if args.command == "scan":
            summary = scan_libraries(conn, settings, logger, dry_run=args.dry_run)
            return 1 if summary["failed"] else 0
        if args.command == "worker":
            try:
                lock_handle = acquire_worker_lock(settings.lock_path)
            except BlockingIOError:
                logger.error("Another converter holds %s", settings.lock_path)
                return 2
            try:
                config_path = os.path.abspath(args.config)
                return run_worker(conn, settings, logger, once=args.once,
                                  reload=lambda: load_settings(config_path))
            finally:
                lock_handle.close()
        if args.command == "extract-subtitles":
            paths = [normalize_path(p) for p in args.paths] or collect_scan_paths(settings, logger)[0]
            counts = extract_subtitles_pass(conn, settings, logger, paths, args.limit, args.dry_run)
            print(json.dumps(counts))
            return 1 if counts["failed"] else 0
        if args.command == "fold-forced":
            counts = fold_forced_sidecars(settings, logger, args.dry_run)
            print(json.dumps(counts))
            return 0
        if args.command == "fix-sidecars":
            paths = [normalize_path(p) for p in args.paths] or collect_scan_paths(settings, logger)[0]
            counts = repair_sidecars_pass(settings, logger, paths, args.dry_run)
            print(json.dumps(counts))
            return 0
        if args.command == "ocr-retry":
            counts = retry_rejected_ocr(settings, logger, args.dry_run)
            print(json.dumps(counts))
            return 1 if counts["failed"] else 0
        if args.command == "enqueue":
            catalog = build_ownership_catalog(settings, logger)
            result = 0
            for raw_path in args.paths:
                path = normalize_path(raw_path)
                if not os.path.isfile(path):
                    logger.error("Cannot enqueue missing file: %s", path)
                    result = 1
                    continue
                signature = SourceSignature.from_path(path)
                owner = choose_owner(
                    path,
                    settings,
                    catalog,
                    stored_owner_for_path(conn, path),
                )
                job_id, created_job = enqueue_job(
                    conn,
                    path,
                    trigger="manual",
                    event_type="Manual",
                    owner=owner,
                    signature=signature,
                    force=args.force,
                )
                print(f"{'Queued' if created_job else 'Updated'} job {job_id}: {path}")
            return result
        if args.command == "validate":
            import validate
            out = args.out or os.path.join(os.path.dirname(settings.database_path), "validation")
            return validate.main((["--sample", args.sample] if args.sample else []) + ["--out", out])
        if args.command == "status":
            snapshot = status_snapshot(conn)
            if args.json:
                print(json.dumps(snapshot, indent=2, sort_keys=True))
            else:
                for section in ("jobs", "callbacks", "hooks"):
                    values = snapshot[section]
                    rendered = " ".join(f"{key}={value}" for key, value in sorted(values.items())) or "none"
                    print(f"{section}: {rendered}")
                for failure in snapshot["failures"]:
                    print(
                        f"failed job={failure['id']} attempts={failure['attempts']} "
                        f"path={failure['path']} error={failure['last_error']}"
                    )
            return 0
        if args.command == "retry":
            if not retry_job(conn, args.job_id):
                print(f"Job {args.job_id} is not failed/cancelled or does not exist", file=sys.stderr)
                return 1
            print(f"Queued job {args.job_id} for retry")
            return 0
    finally:
        conn.close()
    return 2


def main(argv: Optional[Sequence[str]] = None) -> int:
    actual_argv = list(sys.argv[1:] if argv is None else argv)
    if not actual_argv and (
        "sonarr_eventtype" in os.environ or "radarr_eventtype" in os.environ
    ):
        actual_argv = ["hook"]
    parser = build_parser()
    try:
        args = parser.parse_args(actual_argv)
        return command_main(args)
    except (ConfigurationError, PermissionError, RuntimeError, OSError, sqlite3.Error) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
