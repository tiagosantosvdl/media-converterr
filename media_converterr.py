def rollback_installed_output(
    legacy: Any,
    input_path: str,
    output_path: str,
    backup_path: str,
    logger: logging.Logger,
) -> None:
    failed_path = None
    try:
        if os.path.lexists(output_path):
            failed_path = legacy.unique_sidecar_path(output_path, ".failed")
            os.replace(output_path, failed_path)
        os.replace(backup_path, input_path)
        logger.error(
            "Database finalization failed; original restored%s",
            f" and encoded output retained at {failed_path}" if failed_path else "",
        )
    except Exception as error:
        raise RuntimeError(
            f"Could not restore original after database failure; backup={backup_path}: {error}"
        ) from error


