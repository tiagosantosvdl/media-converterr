def ocr_bitmap_subtitles(output_path: str, temps: dict[str, str], settings: Settings, logger: logging.Logger) -> None:
    """Turn copied bitmap streams (.sup for PGS, .mks for VobSub) into SRT temporaries in place in `temps`. A result
    whose mean OCR confidence is too low isn't installed: it goes to `<database dir>/ocr-rejected/<path>` for
    inspection and any existing subtitle stays."""
    import ocr_subtitles
    for suffix, temp in list(temps.items()):
        if not temp.endswith((".sup", ".mks")):
            continue
        srt_temp, ext = temp[:-4], temp[-4:]
        code = suffix.split(".")[1]
        extra = []
        try:
            if ext == ".sup":
                with open(temp, "rb") as f:
                    result = ocr_subtitles.sup_to_srt(f.read(), code)
            else:
                base = temp[:-4] + "-vobsub"  # mkvextract replaces the extension of the name it is given
                extra = [base + ".idx", base + ".sub"]
                subprocess.run(["mkvextract", "-q", temp, "tracks", f"0:{extra[0]}"], capture_output=True, check=True)
                with open(extra[0], encoding="utf-8", errors="replace") as f:
                    idx = f.read()
                with open(extra[1], "rb") as f:
                    result = ocr_subtitles.vobsub_to_srt(idx, f.read(), code)
        except Exception as error:
            kept = os.path.join(os.path.dirname(settings.database_path), "ocr-rejected",
                                (os.path.splitext(output_path)[0] + suffix).lstrip("/") + ext)
            with contextlib.suppress(OSError):
                os.makedirs(os.path.dirname(kept), exist_ok=True)
                shutil.move(temp, kept)
            logger.warning("OCR failed for %s (%s); raw stream kept at %s: %s", suffix, error, kept, output_path)
            del temps[suffix]
            continue
        finally:
            for path in [temp, *extra]:
                try:
                    os.remove(path)
                except OSError:
                    pass
        if result.trusted:
            with open(srt_temp, "w", encoding="utf-8") as f:
                f.write(result.srt)
            temps[suffix] = srt_temp
            logger.info("OCR %s: %d cues, confidence %.0f: %s", suffix, result.cues, result.confidence, output_path)
        else:
            rejected = os.path.join(os.path.dirname(settings.database_path), "ocr-rejected",
                                    (os.path.splitext(output_path)[0] + suffix).lstrip("/"))
            os.makedirs(os.path.dirname(rejected), exist_ok=True)
            with open(rejected, "w", encoding="utf-8") as f:
                f.write(result.srt)
            del temps[suffix]
            logger.warning("OCR %s not installed (%d cues, confidence %.0f below %.0f); saved to %s",
                           suffix, result.cues, result.confidence, ocr_subtitles.MIN_CONFIDENCE, rejected)


def keep_bitmap_sidecars(temps: dict[str, str], logger: logging.Logger) -> None:
    """Bitmap subtitles kept as they are (setting): a PGS stream becomes `<lang>.sup`, a VobSub stream `<lang>.idx`
    with `<lang>.sub` (mkvextract). Renames the entries of `temps` in place."""
    for suffix, temp in list(temps.items()):
        base = suffix[:-4] if suffix.endswith(".srt") else suffix
        if temp.endswith(".sup"):
            del temps[suffix]
            temps[base + ".sup"] = temp
        elif temp.endswith(".mks"):
            del temps[suffix]
            stem = temp[:-4] + "-vobsub"
            try:
                subprocess.run(["mkvextract", "-q", temp, "tracks", f"0:{stem}.idx"], capture_output=True, check=True)
                temps[base + ".idx"], temps[base + ".sub"] = stem + ".idx", stem + ".sub"
            except (OSError, subprocess.CalledProcessError) as error:
                logger.warning("Could not extract VobSub %s: %s", suffix, error)
            finally:
                with contextlib.suppress(OSError):
                    os.remove(temp)


def place_subtitles(output_path: str, temps: dict[str, str], settings: Settings, logger: logging.Logger,
                    fresh: frozenset = frozenset()) -> int:
    """Bitmaps OCR'd or kept as they are (setting), forced tracks folded (SRT only), then installed."""
    if get_legacy_converter().BITMAP_SUBTITLES == "sidecar":
        keep_bitmap_sidecars(temps, logger)
    else:
        ocr_bitmap_subtitles(output_path, temps, settings, logger)
    texts = {k: v for k, v in temps.items() if k.endswith(".srt")}
    others = {k: v for k, v in temps.items() if k not in texts}
    fold_forced_subtitles(output_path, texts, settings, logger, fresh)
    apply_portuguese_policy(output_path, texts, logger)
    temps.clear()
    temps.update(texts)
    temps.update(others)
    return install_subtitles(output_path, temps, settings, logger)


def install_subtitles(output_path: str, temps: dict[str, str], settings: Settings, logger: logging.Logger) -> int:
    """Move extracted subtitles next to the output as `<name><suffix>` (Bazarr naming). A subtitle extracted from the
    release outranks a downloaded one (subtitlerr's source priority: extracted > downloaded > produced), so an existing
    file with that name is replaced; it is moved to `<database dir>/replaced-subtitles/<its path>`, never deleted."""
    backup_root = os.path.join(os.path.dirname(settings.database_path), "replaced-subtitles")
    stem = os.path.splitext(output_path)[0]
    installed = 0
    for suffix, temp in temps.items():
        try:
            if not os.path.isfile(temp) or os.path.getsize(temp) == 0:
                logger.warning("Subtitle %s came out empty; not installed: %s", suffix, output_path)
                continue
            dest = stem + suffix
            if os.path.exists(dest):
                backup = os.path.join(backup_root, dest.lstrip("/"))
                if os.path.exists(backup):
                    backup += f".{int(time.time())}"
                os.makedirs(os.path.dirname(backup), exist_ok=True)
                shutil.move(dest, backup)
                logger.info("Replaced existing subtitle %s (moved to %s)", dest, backup)
            shutil.copyfile(temp, dest + ".tmp")
            os.replace(dest + ".tmp", dest)
            installed += 1
            record_sidecar_inventory(settings.database_path, output_path)
        except OSError as error:
            logger.warning("Could not install subtitle %s for %s: %s", suffix, output_path, error)
        finally:
            try:
                os.remove(temp)
            except OSError:
                pass
    return installed


def _tag_seconds(value: object) -> Optional[float]:
    match = re.match(r"(\d+):(\d+):(\d+(?:\.\d+)?)$", str(value or ""))
    return int(match[1]) * 3600 + int(match[2]) * 60 + float(match[3]) if match else None


def _streams(path: str) -> tuple[list[dict], float]:
    """Streams and the playing time of the video and audio. Subtitle streams are left out of the duration: a subtitle
    can end after the picture, which made the container duration of a file shrink when its subtitles were removed."""
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                          "stream=index,codec_type,duration:stream_tags=DURATION:format=duration",
                          "-of", "json", path], capture_output=True, text=True, check=True).stdout
    data = json.loads(out or "{}")
    streams = data.get("streams", [])
    lengths = []
    for stream in streams:
        if stream.get("codec_type") in ("video", "audio"):
            seconds = stream.get("duration")
            seconds = float(seconds) if seconds not in (None, "N/A") else _tag_seconds((stream.get("tags") or {}).get("DURATION"))
            if seconds:
                lengths.append(seconds)
    return streams, max(lengths) if lengths else float((data.get("format") or {}).get("duration") or 0)


def _packet_count(path: str, index: int) -> int:
    out = subprocess.run(["ffprobe", "-v", "error", "-count_packets", "-select_streams", str(index),
                          "-show_entries", "stream=nb_read_packets", "-of", "csv=p=0", path],
                         capture_output=True, text=True).stdout.strip()
    return int(out) if out.isdigit() else -1


def check_text_extractions(path: str, extractions: Sequence[Any], temps: dict[str, str]) -> None:
    """Raise when a wanted text subtitle came out empty although its source stream has packets: the stream would be
    lost with the remux or the conversion. Streams that really are empty (forced tracks without lines) pass."""
    for extraction in extractions:
        temp = temps.get(extraction.suffix)
        if extraction.kind != "text" or temp is None:
            continue
        if (not os.path.isfile(temp) or os.path.getsize(temp) == 0) and _packet_count(path, extraction.index) != 0:
            raise RuntimeError(f"subtitle stream {extraction.index} ({extraction.suffix}) has content but came out empty")


FULL_TRACK_CUES = 500  # a "forced" track this long is a mislabelled full track (real ones: a few hundred at most)
SHORT_TRACK_CUES = 150    # a regular track with fewer visible cues than this...
SHORT_TRACK_SHARE = 0.25  # ...and under this share of the longest track of the video is an unflagged sign track


def _visible_cues(path: str) -> int:
    import forced_subs
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return sum(1 for c in forced_subs.parse_srt(f.read()) if c.words)
    except OSError:
        return 0


def relabel_brazilian_tracks(output_path: str, temps: dict[str, str], logger: logging.Logger) -> None:
    """Rename pending `.pt` text tracks whose text is Brazilian Portuguese to `.pt-BR`: releases tag both variants
    `por`, and Bazarr, Jellyfin and subtitlerr tell them apart only by the file name. Skipped when the release has a
    `.pt-BR` track of its own."""
    import sidecar_names
    for suffix in [k for k in temps if k.startswith(".pt.") and temps[k].endswith(".srt")]:
        brazilian = ".pt-BR." + suffix[len(".pt."):]
        if brazilian in temps:
            continue
        try:
            with open(temps[suffix], encoding="utf-8", errors="replace") as f:
                language = sidecar_names.detect_language(f.read())
        except OSError:
            continue
        if language == "pt-BR":
            temps[brazilian] = temps.pop(suffix)
            logger.info("Subtitle %s reads as Brazilian Portuguese; installed as %s: %s", suffix, brazilian, output_path)


def _has_brazilian(output_path: str, temps: dict[str, str]) -> bool:
    stem = os.path.splitext(output_path)[0]
    return any(k.startswith(".pt-BR.") for k in temps) or bool(glob.glob(glob.escape(stem) + ".pt-BR*.srt"))


def apply_portuguese_policy(output_path: str, temps: dict[str, str], logger: logging.Logger) -> None:
    """European Portuguese setting for pending subtitles (after Brazilian text was relabelled `.pt-BR`): "never"
    drops `.pt` tracks; "fallback" drops them when the video has a Brazilian track (pending or in the library)."""
    policy = get_legacy_converter().EUROPEAN_PT
    if policy == "always":
        return
    if policy == "fallback" and not _has_brazilian(output_path, temps):
        return
    for suffix in [k for k in temps if k.startswith(".pt.")]:
        with contextlib.suppress(OSError):
            os.remove(temps[suffix])
        del temps[suffix]
        logger.info("European Portuguese subtitle %s not installed (setting: %s): %s", suffix, policy, output_path)


def retire_european_portuguese(video_path: str, settings: Settings, logger: logging.Logger) -> int:
    """Library side of the European Portuguese setting, run by the scan: `.pt` sidecars of a video that has a
    Brazilian one ("fallback") or any ("never") move to `<database dir>/replaced-subtitles/` (never deleted)."""
    policy = get_legacy_converter().EUROPEAN_PT
    if policy == "always":
        return 0
    stem = os.path.splitext(video_path)[0]
    european = glob.glob(glob.escape(stem) + ".pt.srt") + glob.glob(glob.escape(stem) + ".pt.*.srt")
    if not european or (policy == "fallback" and not glob.glob(glob.escape(stem) + ".pt-BR*.srt")):
        return 0
    backup_root = os.path.join(os.path.dirname(settings.database_path), "replaced-subtitles")
    moved = 0
    for path in european:
        backup = os.path.join(backup_root, path.lstrip("/"))
        try:
            os.makedirs(os.path.dirname(backup), exist_ok=True)
            shutil.move(path, backup + (f".{int(time.time())}" if os.path.exists(backup) else ""))
            moved += 1
            logger.info("European Portuguese subtitle moved aside (setting: %s): %s", policy, path)
        except OSError as error:
            logger.warning("Could not move %s aside: %s", path, error)
    return moved


def mark_short_tracks_forced(output_path: str, temps: dict[str, str], logger: logging.Logger) -> None:
    """Relabel pending regular text tracks that are really unflagged forced (sign) tracks as `.forced`, so
    fold_forced_subtitles merges or archives them instead of installing them: some releases carry only a signs track
    for a language, unflagged, and an installed one hides the missing subtitle from Bazarr. A track counts as one
    with fewer than SHORT_TRACK_CUES visible cues and under SHORT_TRACK_SHARE of the longest other track of the video
    (pending or already beside it). Sidecars already in the library are never relabelled here."""
    import forced_subs
    stem = os.path.splitext(output_path)[0]
    counts = {k: _visible_cues(v) for k, v in temps.items() if v.endswith(".srt") and os.path.isfile(v)}
    for path in glob.glob(glob.escape(stem) + ".*.srt"):
        suffix = path[len(stem):]
        if ".forced." not in suffix and suffix not in counts:
            counts[suffix] = _visible_cues(path)
    for suffix in [k for k in temps if ".forced." not in k and k in counts and temps[k] != stem + k]:
        others = [n for k, n in counts.items() if k != suffix and ".forced." not in k]
        n = counts[suffix]
        if not others or n >= SHORT_TRACK_CUES or n >= SHORT_TRACK_SHARE * max(others):
            continue
        forced = suffix[:-len(".srt")] + ".forced.srt"
        temp = temps.pop(suffix)
        if forced in temps:  # a flagged forced track as well: keep one, with the cues of both
            with open(temp, encoding="utf-8", errors="replace") as f:
                short_text = f.read()
            with open(temps[forced], encoding="utf-8", errors="replace") as f:
                merged, _ = forced_subs.merge(short_text, f.read())
            with open(temps[forced], "w", encoding="utf-8") as f:
                f.write(merged)
            os.remove(temp)
        else:
            temps[forced] = temp
        logger.info("Subtitle %s has %d visible cue(s) against %d in the longest track: treated as forced: %s",
                    suffix, n, max(others), output_path)


def fold_forced_subtitles(output_path: str, temps: dict[str, str], settings: Settings, logger: logging.Logger,
                          fresh: frozenset = frozenset()) -> list[str]:
    """Merge forced subtitles into the full tracks of their language and drop them (user decision: no .forced.srt in
    the library). A forced cue is added to the regular and HI track (pending in `temps`, or already beside the video)
    when no cue around the same time says the same thing. Every forced track is archived under
    `<database dir>/forced-subtitles/`; a full track already in the library is backed up to `replaced-subtitles/`
    before it changes, unless it is in `fresh` (installed by this same run).

    A "forced" track with FULL_TRACK_CUES or more cues is a mislabelled full track (some releases flag their only
    track of a language as forced). Without a regular track of that language from the same release it becomes the
    regular track (`temps` entry renamed; installing it replaces a downloaded one, with a backup). For a sidecar
    already in the library (`temps` points at the library file itself) the origin of an existing regular track is
    unknown, so it is left in place and its suffix returned for review. Pending regular tracks that are really
    unflagged sign tracks are relabelled first (mark_short_tracks_forced), and so are Brazilian tracks tagged as
    Portuguese (relabel_brazilian_tracks)."""
    import forced_subs
    relabel_brazilian_tracks(output_path, temps, logger)
    mark_short_tracks_forced(output_path, temps, logger)
    stem = os.path.splitext(output_path)[0]
    data_dir = os.path.dirname(settings.database_path)
    review = []
    for suffix in [k for k in temps if ".forced." in k]:
        temp = temps.pop(suffix)
        try:
            with open(temp, encoding="utf-8", errors="replace") as f:
                forced_text = f.read()
        except OSError:
            forced_text = ""
        regular = suffix.replace(".forced", "")
        if len(forced_subs.parse_srt(forced_text)) >= FULL_TRACK_CUES:
            in_library = temp == stem + suffix
            if in_library and os.path.exists(stem + regular):
                logger.warning("Forced subtitle %s looks like a full track and %s exists; left for review: %s",
                               suffix, regular, output_path)
                review.append(suffix)
                continue
            if in_library:
                os.replace(temp, stem + regular)
                logger.info("Forced subtitle %s is a full track; installed as %s: %s", suffix, regular, output_path)
                continue
            if regular not in temps and stem + regular not in fresh:
                temps[regular] = temp
                logger.info("Forced subtitle %s is a full track; used as %s: %s", suffix, regular, output_path)
                continue
        lang = "." + suffix.split(".")[1]
        targets = 0
        for full_suffix in (lang + ".srt", lang + ".hi.srt"):
            pending = temps.get(full_suffix)
            target = pending if pending and os.path.isfile(pending) else stem + full_suffix
            if not os.path.isfile(target):
                continue
            targets += 1
            with open(target, encoding="utf-8", errors="replace") as f:
                full_text = f.read()
            merged, added = forced_subs.merge(forced_text, full_text)
            if not added:
                continue
            if target == stem + full_suffix and target not in fresh:
                backup = os.path.join(data_dir, "replaced-subtitles", target.lstrip("/"))
                if os.path.exists(backup):
                    backup += f".{int(time.time())}"
                os.makedirs(os.path.dirname(backup), exist_ok=True)
                shutil.copy2(target, backup)
            with open(target + ".tmp", "w", encoding="utf-8") as f:
                f.write(merged)
            os.replace(target + ".tmp", target)
            logger.info("Merged %d forced cue(s) from %s into %s: %s", added, suffix, full_suffix, output_path)
        try:
            if forced_text.strip():
                archive = os.path.join(data_dir, "forced-subtitles", (stem + suffix).lstrip("/"))
                os.makedirs(os.path.dirname(archive), exist_ok=True)
                shutil.move(temp, archive)
                if not targets:
                    logger.warning("Forced subtitle %s has no full track to merge into; archived at %s: %s",
                                   suffix, archive, output_path)
            else:
                os.remove(temp)
        except OSError as error:
            logger.warning("Could not archive forced subtitle %s for %s: %s", suffix, output_path, error)
    return review


def strip_subtitles(conn: sqlite3.Connection, path: str, settings: Settings, catalog: "OwnershipCatalog",
                    logger: logging.Logger, dry_run: bool = False,
                    background: Optional[Callable[[Callable[[], None]], None]] = None) -> str:
    """Move a library file's embedded subtitles out: the wanted ones become sidecar .srt files (bitmaps OCR'd, a
    release subtitle replacing a downloaded one), and the file is remuxed without any subtitle stream. Video, audio,
    attachments, chapters and metadata are copied unchanged. The remux is written beside the original as a hidden
    `.<name>.partial` (not a video name, so Sonarr/Radarr never import it) and renamed over it after the checks.
    Bitmap OCR runs after the swap, through `background` when given (the pass overlaps it with the next remux).
    Returns what happened ("none", "dry-run", "done")."""
    legacy = get_legacy_converter()
    streams, duration = _streams(path)
    kinds = [s.get("codec_type") for s in streams]
    if "subtitle" not in kinds:
        return "none"
    extractions = legacy.subtitle_extractions(path)
    if dry_run:
        logger.info("Would extract %d of %d subtitle streams: %s", len(extractions), kinds.count("subtitle"), path)
        return "dry-run"
    start = SourceSignature.from_path(path)
    temp_base = os.path.join(settings.work_dir, f"strip.{os.getpid()}.{uuid.uuid4().hex}.mkv")
    staged = os.path.join(os.path.dirname(path), f".{os.path.basename(path)}.partial")  # not a video name: arrs ignore it
    sub_args, temps = legacy.subtitle_output_args(extractions, temp_base)
    os.makedirs(settings.work_dir, exist_ok=True)
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-i", path,
           "-map", "0:v", "-map", "0:a?", "-map", "0:t?", "-c", "copy", "-map_metadata", "0", "-map_chapters", "0",
           "-f", "matroska", staged, *sub_args]
    if shutil.which("ionice"):
        cmd = ["ionice", "-c2", "-n7", *cmd]
    try:
        code, log = legacy.run(cmd, settings.work_dir, logger)
        if STOP_REQUESTED:
            raise WorkerStopping()
        if code != 0:
            raise RuntimeError(f"ffmpeg exit {code}: {(log.strip().splitlines() or ['no error text'])[-1]}")
        new_streams, new_duration = _streams(staged)
        new_kinds = [s.get("codec_type") for s in new_streams]
        if ("subtitle" in new_kinds or new_kinds.count("video") != kinds.count("video")
                or new_kinds.count("audio") != kinds.count("audio") or abs(new_duration - duration) > 1.0):
            raise RuntimeError(f"remux check failed: streams {new_kinds} vs {kinds}, duration {new_duration} vs {duration}")
        check_text_extractions(path, extractions, temps)
        if SourceSignature.from_path(path) != start:
            raise SourceChangedError("source changed during the subtitle pass")
        os.replace(staged, path)
    except BaseException:
        for leftover in [staged, *temps.values()]:
            try:
                os.remove(leftover)
            except OSError:
                pass
        raise
    row = get_file_row(conn, path)
    owner = choose_owner(path, settings, catalog, owner_from_row(row))
    if row is not None and row["status"] == "ok":  # keep our record (and its note) in step with the new file
        with conn:
            upsert_file(conn, path, SourceSignature.from_path(path), status="ok", note=row["note"], owner=owner)
    if owner is not None:
        with conn:
            enqueue_callback(conn, owner, time.time() + settings.callback_delay_seconds)
    bitmaps = {k: v for k, v in temps.items() if v.endswith((".sup", ".mks"))}
    texts = {k: v for k, v in temps.items() if k not in bitmaps}
    fold_forced_subtitles(path, texts, settings, logger)
    installed = install_subtitles(path, texts, settings, logger)
    fresh = frozenset(os.path.splitext(path)[0] + k for k in texts)

    def finish() -> None:  # no database access here: it may run on the OCR thread
        done = installed
        if bitmaps:
            done += place_subtitles(path, bitmaps, settings, logger, fresh)
        logger.info("Subtitles moved out: %d of %d streams extracted (%s), file remuxed without subtitles: %s",
                    done, kinds.count("subtitle"), ", ".join(e.suffix for e in extractions) or "none wanted", path)
        jellyfin_media_updated(settings, [path], logger)

    (background or (lambda fn: fn()))(finish)
    return "done"


FORCED_SIDECAR = re.compile(r"^(?P<stem>.+)(?P<suffix>\.[A-Za-z]{2,3}(?:-[A-Za-z]{2})?(?:\.hi)?\.forced\.srt)$")


def fold_forced_sidecars(settings: Settings, logger: logging.Logger, dry_run: bool = False) -> dict[str, int]:
    """One-off cleanup: run fold_forced_subtitles over every `.forced.srt` already in the library folders."""
    import forced_subs
    counts = {"forced": 0, "cues added": 0, "no full track": 0, "full track": 0, "review": 0}
    for base in settings.scan_roots:
        for root, dirs, files in os.walk(base):
            dirs[:] = [d for d in dirs if d not in settings.exclude]
            for name in files:
                match = FORCED_SIDECAR.match(name)
                if not match:
                    continue
                counts["forced"] += 1
                sidecar = os.path.join(root, name)
                video = os.path.join(root, match["stem"] + ".mkv")  # only its stem is used
                with open(sidecar, encoding="utf-8", errors="replace") as f:
                    long_track = len(forced_subs.parse_srt(f.read())) >= FULL_TRACK_CUES
                if long_track:
                    regular = os.path.join(root, match["stem"] + match["suffix"].replace(".forced", ""))
                    counts["review" if os.path.exists(regular) else "full track"] += 1
                    if dry_run:
                        logger.info("Would %s: %s", "leave for review" if os.path.exists(regular)
                                    else "install as the regular track", sidecar)
                        continue
                if dry_run:
                    lang = "." + match["suffix"].split(".")[1]
                    fulls = [os.path.join(root, match["stem"] + lang + s) for s in (".srt", ".hi.srt")]
                    fulls = [f for f in fulls if os.path.isfile(f)]
                    if not fulls:
                        counts["no full track"] += 1
                    with open(sidecar, encoding="utf-8", errors="replace") as f:
                        forced = forced_subs.parse_srt(f.read())
                    for full in fulls:
                        with open(full, encoding="utf-8", errors="replace") as f:
                            add = forced_subs.missing_cues(forced, forced_subs.parse_srt(f.read()))
                        counts["cues added"] += len(add)
                        if add:
                            logger.info("Would merge %d forced cue(s) into %s", len(add), full)
                    continue
                fold_forced_subtitles(video, {match["suffix"]: sidecar}, settings, logger)
    logger.info("Forced subtitle cleanup%s: %s", " (dry run)" if dry_run else "", counts)
    return counts


def _sha1(path: str) -> Optional[str]:
    import hashlib
    try:
        with open(path, "rb") as handle:
            return hashlib.sha1(handle.read()).hexdigest()
    except OSError:
        return None


def record_sidecar_inventory(database_path: str, video_path: str) -> int:
    """Remember the properly named subtitle files of a video by content (folder, SHA-1 -> suffix), so a rename that
    mangles their names (Sonarr/Radarr drop `pt-BR` entirely: `.pt-BR.hi.srt` becomes `.hi.srt`) can be undone
    exactly. Refreshed by every scan and after subtitles are installed or repaired. Returns the files recorded."""
    import sidecar_names
    folder, stem = os.path.split(os.path.splitext(video_path)[0])
    try:
        names = os.listdir(folder)
    except OSError:
        return 0
    rows = []
    for name in names:
        if not name.startswith(stem + ".") or not name.lower().endswith(".srt"):
            continue
        suffix = name[len(stem):-4]
        if not sidecar_names.is_valid_suffix(suffix):
            continue
        digest = _sha1(os.path.join(folder, name))
        if digest:
            rows.append((folder, digest, suffix, stem, time.time()))
    if not rows:
        return 0
    try:
        conn = sqlite3.connect(database_path, timeout=30)
        with conn:
            conn.executemany("INSERT INTO sidecar_inventory(folder, sha1, suffix, video, updated_at) VALUES(?,?,?,?,?) "
                             "ON CONFLICT(folder, sha1) DO UPDATE SET suffix=excluded.suffix, video=excluded.video, "
                             "updated_at=excluded.updated_at", rows)
        conn.close()
    except sqlite3.Error:
        return 0
    return len(rows)


def remembered_suffix(database_path: str, path: str) -> Optional[str]:
    """The suffix this subtitle file (by content) had when last seen properly named in its folder."""
    digest = _sha1(path)
    if not digest or not os.path.isfile(database_path):
        return None
    try:
        conn = sqlite3.connect(f"file:{database_path}?mode=ro", uri=True, timeout=30)
        row = conn.execute("SELECT suffix FROM sidecar_inventory WHERE folder=? AND sha1=?",
                           (os.path.dirname(path), digest)).fetchone()
        conn.close()
    except sqlite3.Error:
        return None
    return row[0] if row else None


def repair_sidecars(video_path: str, settings: Settings, logger: logging.Logger, dry_run: bool = False) -> dict[str, int]:
    """Put back the sidecar names a Sonarr/Radarr rename mangled (`sidecar_names`): the language from the text, the
    hearing-impaired and forced flags from the surviving tags. A mangled file whose proper name is taken by a file
    with the same lines (timing may differ: the copy with the proper name is the one Bazarr knows and syncs) is a
    duplicate and goes to `<database dir>/odd-sidecars/<path>`; one whose language is unclear
    or whose proper name holds a different text is left alone with a warning."""
    import sidecar_names
    counts = {"renamed": 0, "duplicate": 0, "unclear": 0, "conflict": 0}
    folder = os.path.dirname(video_path)
    try:
        names = os.listdir(folder)
    except OSError:
        return counts
    planned: dict[str, str] = {}  # target -> text, so a dry run sees its own earlier renames
    for name, suffix in sidecar_names.mangled_sidecars(video_path, names):
        source = os.path.join(folder, name)
        try:
            with open(source, encoding="utf-8", errors="replace") as handle:
                text = handle.read()
        except OSError:
            continue
        remembered = remembered_suffix(settings.database_path, source)
        language = None if remembered else (sidecar_names.tagged_language(suffix)
                                            or sidecar_names.detect_language(text))
        if not remembered and not language:
            counts["unclear"] += 1
            logger.warning("Sidecar %s: language unclear, name left as is", source)
            continue
        target = os.path.splitext(video_path)[0] + (remembered or sidecar_names.repaired_suffix(suffix, language)) + ".srt"
        if target in planned or os.path.exists(target):
            if target in planned:
                same = sidecar_names.same_lines(planned[target], text)
            else:
                with open(target, encoding="utf-8", errors="replace") as handle:
                    same = sidecar_names.same_lines(handle.read(), text)
            if not same:
                counts["conflict"] += 1
                logger.warning("Sidecar %s should be %s, which holds another text; left as is", source, target)
                continue
            counts["duplicate"] += 1
            if not dry_run:
                stash = os.path.join(os.path.dirname(settings.database_path), "odd-sidecars", source.lstrip("/"))
                os.makedirs(os.path.dirname(stash), exist_ok=True)
                shutil.move(source, stash)
            logger.info("Sidecar %s duplicates %s%s", source, os.path.basename(target), "" if dry_run else "; moved aside")
            continue
        counts["renamed"] += 1
        planned[target] = text
        if not dry_run:
            os.rename(source, target)
            record_sidecar_inventory(settings.database_path, video_path)
        logger.info("Sidecar %s %s %s", source, "would be renamed to" if dry_run else "renamed to", os.path.basename(target))
    return counts


def jellyfin_media_updated(settings: Settings, paths: Sequence[str], logger: logging.Logger,
                           deleted: Sequence[str] = ()) -> None:
    """Tell Jellyfin these local paths changed, or are gone (`/Library/Media/Updated`, what Sonarr/Radarr's own
    connection sends), so it rescans their items at once instead of relying on its file watcher. Paths outside the
    configured roots are skipped; a failure is only logged."""
    jellyfin = getattr(settings, "jellyfin", None)
    if not jellyfin or not (paths or deleted):
        return
    updates = []
    for path, kind in [(p, "Modified") for p in paths] + [(p, "Deleted") for p in deleted]:
        for local, remote in jellyfin.paths:
            if path == local or path.startswith(local.rstrip("/") + "/"):
                updates.append({"Path": remote.rstrip("/") + path[len(local.rstrip("/")):], "UpdateType": kind})
                break
    for start in range(0, len(updates), 100):
        request = urllib.request.Request(
            f"{jellyfin.url}/Library/Media/Updated", method="POST",
            data=json.dumps({"Updates": updates[start:start + 100]}).encode("utf-8"),
            headers={"Authorization": f'MediaBrowser Token="{jellyfin.api_key}"', "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(request, timeout=settings.api_timeout_seconds):
                pass
        except (urllib.error.URLError, OSError) as error:
            logger.warning("Jellyfin update notification failed: %s", error)
            return
    if updates:
        logger.info("Told Jellyfin about %d updated item(s)", len(updates))


def follow_rename(path: str, previous: Optional[str], settings: Settings, logger: logging.Logger) -> int:
    """Move sidecars still named after the video's previous path to its new name, suffix unchanged. Sonarr/Radarr
    only move the sidecars they have on record, and after a repair their record still holds the mangled names, so
    the repaired files stay behind. A copy whose new name already holds the same lines goes to `odd-sidecars/`; a
    different text there is left alone with a warning. Returns how many files were moved or set aside."""
    if not previous or previous == path or os.path.exists(previous):
        return 0
    old_stem, new_stem = os.path.splitext(previous)[0], os.path.splitext(path)[0]
    folder = os.path.dirname(previous)
    try:
        names = sorted(os.listdir(folder))
    except OSError:
        return 0
    import sidecar_names
    others = [os.path.join(folder, os.path.splitext(n)[0]) for n in names if n.lower().endswith(sidecar_names.VIDEO_EXTENSIONS)]
    moved = 0
    for name in names:
        source = os.path.join(folder, name)
        if not source.startswith(old_stem + ".") or not name.lower().endswith(".srt"):
            continue
        if any(len(o) > len(old_stem) and source.startswith(o + ".") for o in others):
            continue
        target = new_stem + source[len(old_stem):]
        if os.path.exists(target):
            with open(source, encoding="utf-8", errors="replace") as a, open(target, encoding="utf-8", errors="replace") as b:
                same = sidecar_names.same_lines(a.read(), b.read())
            if not same:
                logger.warning("Sidecar %s left behind by a rename; %s holds another text, left as is", source, target)
                continue
            stash = os.path.join(os.path.dirname(settings.database_path), "odd-sidecars", source.lstrip("/"))
            os.makedirs(os.path.dirname(stash), exist_ok=True)
            shutil.move(source, stash)
            logger.info("Sidecar %s left behind by a rename duplicates %s; moved aside", source, os.path.basename(target))
        else:
            os.makedirs(os.path.dirname(target), exist_ok=True)
            shutil.move(source, target)
            logger.info("Sidecar %s left behind by a rename; moved to %s", source, os.path.basename(target))
        moved += 1
    return moved


def repair_after_rename(pairs: Sequence[tuple[str, Optional[str]]], settings: Settings, logger: logging.Logger,
                        folder: Optional[str] = None) -> None:
    """Rename hook: bring along sidecars left under the previous name, repair the renamed videos' sidecar names, then
    let Jellyfin rescan the ones that changed. With `folder` (the series or movie folder), the sidecars of every
    other video there are repaired too: Sonarr rewrites the extra files of the whole series on a rename, mangling
    those of episodes whose video kept its name, while its event lists only the renamed videos (seen live). Never
    fails the hook event."""
    changed = []
    others = []
    if folder and os.path.isdir(folder):
        named = {path for path, _ in pairs}
        for root, _, files in os.walk(folder):
            others += [(os.path.join(root, f), None) for f in files
                       if os.path.splitext(f)[1].lower().lstrip(".") in sidecar_names_video_extensions()
                       and not f.startswith(".") and os.path.join(root, f) not in named]
    for path, previous in [*pairs, *others]:
        try:
            followed = follow_rename(path, previous, settings, logger)
            counts = repair_sidecars(path, settings, logger)
        except Exception as error:  # a repair problem must not block the event queue
            logger.warning("Sidecar repair failed for %s: %s", path, error)
            continue
        if followed or counts["renamed"] or counts["duplicate"]:
            changed.append(path)
    jellyfin_media_updated(settings, changed, logger)


def sidecar_names_video_extensions() -> set[str]:
    import sidecar_names
    return {e.lower().lstrip(".") for e in sidecar_names.VIDEO_EXTENSIONS}


def repair_sidecars_pass(settings: Settings, logger: logging.Logger, paths: Sequence[str],
                         dry_run: bool = False) -> dict[str, int]:
    """`fix-sidecars`: repair mangled sidecar names for `paths` (videos or folders; default: every library video)."""
    import sidecar_names
    totals = {"videos": 0, "renamed": 0, "duplicate": 0, "unclear": 0, "conflict": 0}
    changed = []
    videos = []
    for path in paths:
        if os.path.isdir(path):
            videos += sorted(os.path.join(d, f) for d, _, files in os.walk(path) for f in files
                             if f.lower().endswith(sidecar_names.VIDEO_EXTENSIONS) and not f.startswith("."))
        else:
            videos.append(path)
    for path in videos:
        counts = repair_sidecars(path, settings, logger, dry_run)
        totals["videos"] += 1
        for key, value in counts.items():
            totals[key] += value
        if counts["renamed"] or counts["duplicate"]:
            changed.append(path)
    if not dry_run:
        jellyfin_media_updated(settings, changed, logger)
    logger.info("Sidecar repair%s: %s", " (dry run)" if dry_run else "", totals)
    return totals


RAW_SUBTITLE = re.compile(r"^(?P<stem>.+?)(?P<suffix>\.[A-Za-z]{2,3}(?:-[A-Za-z]{2})?(?:\.hi)?(?:\.forced)?\.srt)"
                          r"(?P<ext>\.sup|\.mks)$")


def retry_rejected_ocr(settings: Settings, logger: logging.Logger, dry_run: bool = False) -> dict[str, int]:
    """OCR again the raw bitmap streams kept in `<database dir>/ocr-rejected/` after a failed OCR, and install the
    results next to their videos as a conversion would (forced folded, existing subtitle backed up). A raw stream
    whose video is gone is left alone; one that fails again stays where it is."""
    rejected_root = os.path.join(os.path.dirname(settings.database_path), "ocr-rejected")
    counts = {"raw": 0, "installed": 0, "low confidence": 0, "failed": 0, "no video": 0}
    for root, _dirs, files in os.walk(rejected_root):
        for name in sorted(files):
            match = RAW_SUBTITLE.match(name)
            if not match:
                continue
            counts["raw"] += 1
            raw = os.path.join(root, name)
            stem = "/" + os.path.relpath(os.path.join(root, match["stem"]), rejected_root)
            videos = [f"{stem}.{e}" for e in settings.convertible_extensions if os.path.isfile(f"{stem}.{e}")]
            if not videos:
                counts["no video"] += 1
                logger.warning("OCR retry: no video for %s", raw)
                continue
            if dry_run:
                continue
            temp = os.path.join(settings.work_dir, f"ocr-retry.{uuid.uuid4().hex}{match['suffix']}{match['ext']}")
            shutil.copyfile(raw, temp)
            text = os.path.join(rejected_root, (stem + match["suffix"]).lstrip("/"))  # where low-confidence OCR goes
            before = os.stat(text).st_mtime_ns if os.path.exists(text) else None
            temps = {match["suffix"]: temp}
            ocr_bitmap_subtitles(videos[0], temps, settings, logger)
            if match["suffix"] not in temps:
                if os.path.exists(text) and os.stat(text).st_mtime_ns != before:  # low confidence: text saved there
                    counts["low confidence"] += 1
                    os.remove(raw)
                else:  # failed again: the copy was moved back over the raw stream
                    counts["failed"] += 1
                continue
            fold_forced_subtitles(videos[0], temps, settings, logger)
            install_subtitles(videos[0], temps, settings, logger)
            os.remove(raw)
            counts["installed"] += 1
            jellyfin_media_updated(settings, [videos[0]], logger)
    logger.info("OCR retry%s: %s", " (dry run)" if dry_run else "", counts)
    return counts


def extract_subtitles_pass(conn: sqlite3.Connection, settings: Settings, logger: logging.Logger, paths: list[str],
                           limit: Optional[int] = None, dry_run: bool = False) -> dict[str, int]:
    """Run strip_subtitles over `paths` (default: every scan candidate), one file at a time, taking the GPU lock per
    file so it never overlaps a conversion. Each file's bitmap OCR runs on one background thread while the next file
    is remuxed; at most one OCR job is pending, and the pass waits for it before finishing or stopping."""
    global STOP_REQUESTED
    counts = {"files": len(paths), "done": 0, "none": 0, "dry-run": 0, "failed": 0}
    if get_legacy_converter().SUBTITLE_MODE == "embed":
        logger.warning("Subtitle pass skipped: subtitles are set to stay in the container")
        return counts
    STOP_REQUESTED = False
    signal.signal(signal.SIGINT, request_worker_stop)
    signal.signal(signal.SIGTERM, request_worker_stop)
    catalog = build_ownership_catalog(settings, logger)
    gpu = GpuLock(os.environ.get("GPU_LOCK"))
    ocr_pool = concurrent.futures.ThreadPoolExecutor(max_workers=1, thread_name_prefix="ocr")
    pending: list[concurrent.futures.Future] = []

    def wait_pending() -> None:
        while pending:
            try:
                pending.pop().result()
            except Exception as error:
                logger.warning("Subtitle OCR task failed: %s", error)

    def background(fn: Callable[[], None]) -> None:
        wait_pending()
        pending.append(ocr_pool.submit(fn))

    for n, path in enumerate(paths, 1):
        if STOP_REQUESTED or (limit is not None and counts["done"] + counts["dry-run"] >= limit):
            break
        while not dry_run and not gpu.try_acquire():
            time.sleep(10)
        try:
            counts[strip_subtitles(conn, path, settings, catalog, logger, dry_run, background)] += 1
        except WorkerStopping:
            break
        except Exception as error:
            counts["failed"] += 1
            logger.warning("Subtitle pass failed for %s: %s", path, error)
        finally:
            if not dry_run:
                gpu.release()
        if n % 50 == 0:
            logger.info("Subtitle pass: %d/%d files, %s", n, len(paths), counts)
    wait_pending()
    ocr_pool.shutdown()
    logger.info("Subtitle pass finished: %s", counts)
    return counts


PROGRESS_FILE = "progress.txt"   # ffmpeg -progress output of the running encode or remux (in the work dir)
PROGRESS_META = "progress.json"  # which file it is and how long it plays, for the web interface


def _write_meta(settings: Settings, **fields: Any) -> None:
    """Merge fields into the running job's note for the web interface (progress.json)."""
    path = os.path.join(settings.work_dir, PROGRESS_META)
    try:
        with open(path, encoding="utf-8") as handle:
            meta = json.load(handle)
    except (OSError, ValueError):
        meta = {}
    if fields.get("path") and meta.get("path") != fields["path"]:
        meta = {}  # another job's note
    meta.update(fields)
    with contextlib.suppress(OSError):
        with open(path + ".tmp", "w", encoding="utf-8") as handle:
            json.dump(meta, handle)
        os.replace(path + ".tmp", path)


def job_steps(video_info: Any, mode: str, remux: Optional[str], subtitles: Sequence[Any]) -> list[str]:
    """The steps of one conversion, as the web interface shows them ("(2/5) Injecting Dolby Vision")."""
    legacy = get_legacy_converter()
    steps = ["Remuxing" if remux else "Converting"]
    if not remux:
        spec = legacy.output_spec(video_info, mode)
        hevc = legacy.output_codec(mode, video_info) == "hevc"
        if hevc and spec.target in ("hdr10plus", "dv81") and video_info.hdr10_plus:
            steps.append("Injecting HDR10+")
        if hevc and spec.target == "dv81":
            steps.append("Injecting Dolby Vision")
    steps += ["Checking output", "Installing"]
    if subtitles:
        steps.append("Subtitles")
    return steps


def set_stage(settings: Settings, input_path: str, steps: list[str], stage: str) -> None:
    _write_meta(settings, path=input_path, steps=steps, stage=stage,
                step=steps.index(stage) + 1 if stage in steps else 0)


def with_progress(command: list[str], input_path: str, settings: Settings, kind: str) -> list[str]:
    """The ffmpeg command with -progress reporting into the work dir, and the note the web interface reads beside
    it (source path, playing time, what is running). Real progress: encoded position over the source's duration."""
    try:
        duration = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of",
                                         "csv=p=0", input_path], capture_output=True, text=True).stdout.strip())
    except ValueError:
        duration = 0.0
    progress = os.path.join(settings.work_dir, PROGRESS_FILE)
    with contextlib.suppress(OSError):
        os.remove(progress)
    _write_meta(settings, path=input_path, duration=duration, kind=kind, started=time.time())
    return [command[0], "-progress", progress, "-stats_period", "5", *command[1:]]


def encode_video(input_path: str, temp_path: str, video_info: Any, mode: str, extra_args: Sequence[str],
                 settings: Settings, logger: logging.Logger,
                 stage: Optional[Callable[[str], None]] = None) -> None:
    """The encode itself: hardware first, software decode/filter fallback, then HDR10+ injection for HEVC outputs.
    Raises on failure; validation and installation are the caller's."""
    legacy = get_legacy_converter()
    command = with_progress(legacy.build_cmd(input_path, temp_path, False, video_info) + list(extra_args),
                            input_path, settings, "encode")
    logger.warning("Encoding start: %s", input_path)
    logger.info("Encoding cmd: %s (cwd=%s)", legacy.command_text(command), settings.work_dir)
    return_code, command_log = legacy.run(command, settings.work_dir, logger)
    logger.info("Encoding exit: %d", return_code)
    if STOP_REQUESTED:
        raise WorkerStopping()
    if return_code != 0:
        logger.warning("Encoding failed. Retrying with software decode/filter fallback.")
        command = with_progress(legacy.build_cmd(input_path, temp_path, True, video_info) + list(extra_args),
                                input_path, settings, "encode")
        logger.warning("Encoding start: %s", input_path)
        logger.info(
            "Encoding cmd: %s (cwd=%s)", legacy.command_text(command), settings.work_dir
        )
        return_code, command_log = legacy.run(command, settings.work_dir, logger)
        logger.info("Encoding exit: %d", return_code)
    if STOP_REQUESTED:
        raise WorkerStopping()
    if return_code != 0:
        detail = command_log.strip().splitlines()
        raise RuntimeError(
            f"ffmpeg exit {return_code}: "
            f"{detail[-1] if detail else 'no ffmpeg error text'}"
        )

    spec = legacy.output_spec(video_info, mode)
    hevc = legacy.output_codec(mode, video_info) == "hevc"
    if spec.target in ("hdr10plus", "dv81") and video_info.hdr10_plus:
        if hevc and stage:
            stage("Injecting HDR10+")
        if hevc and legacy.inject_hdr10plus(input_path, temp_path, settings.work_dir, logger):
            logger.info("HDR10+ metadata injected: %s", input_path)
    if spec.target == "dv81":
        if hevc and stage:
            stage("Injecting Dolby Vision")
        if hevc and legacy.inject_dovi(input_path, temp_path, settings.work_dir, logger):
            logger.info("Dolby Vision profile 8.1 injected: %s", input_path)
        elif not hevc:
            logger.warning("Dolby Vision needs HEVC output; encoded as HDR10: %s", input_path)
    elif video_info.dovi_profile is not None and not spec.tonemap:
        logger.info("Dolby Vision encoded as HDR10 from its base layer (setting): %s", input_path)
    elif spec.tonemap:
        logger.info("HDR tone mapped to SDR (setting): %s", input_path)


def process_conversion_job(
    conn: sqlite3.Connection,
    row: sqlite3.Row,
    settings: Settings,
    catalog: OwnershipCatalog,
    logger: logging.Logger,
) -> None:
    legacy = get_legacy_converter()
    job_id = int(row["id"])
    input_path = normalize_path(row["path"])
    if not os.path.isfile(input_path):
        cancel_job(conn, job_id, "source file is missing")
        logger.warning("Cancelled missing job=%d path=%s", job_id, input_path)
        return

    start_signature = SourceSignature.from_path(input_path)
    existing = get_file_row(conn, input_path)
    owner = job_owner(row) or owner_from_row(existing)
    owner = choose_owner(input_path, settings, catalog, owner)

    verified = lookup_verified_file(conn, input_path, start_signature)
    renamed_from = None
    if verified is None:
        renamed_from = reconcile_rename(
            conn,
            input_path,
            start_signature,
            previous_path=row["previous_path"],
        )
        if renamed_from:
            logger.info("DB path updated after rename: %s -> %s", renamed_from, input_path)
            verified = lookup_verified_file(conn, input_path, start_signature)
            if owner is None:
                owner = stored_owner_for_path(conn, input_path)

    forced = bool(row["force"]) if "force" in row.keys() else False
    if verified is not None and not forced:
        update_file_owner(conn, input_path, owner)
        finish_job(conn, job_id, output_path=input_path, skipped=True)
        logger.info("Skip (database verified): %s", input_path)
        return
    own = None if forced else converter_output(conn, input_path, start_signature)
    if own:
        refresh_own_output(conn, input_path, start_signature, owner, own)
        finish_job(conn, job_id, output_path=input_path, skipped=True)
        logger.info("Skip (converter output, %s; re-encode only on request): %s", own, input_path)
        return
    if forced:
        logger.warning("Re-encode requested: %s", input_path)

    output_path = normalize_path(legacy.to_target_naming(input_path))
    legacy.ensure_output_path_available(input_path, output_path)
    os.makedirs(settings.work_dir, exist_ok=True)
    temp_path = os.path.join(
        settings.work_dir,
        f"temp.converterr.{os.getpid()}.{job_id}.{uuid.uuid4().hex}.mkv",
    )
    if os.path.lexists(temp_path):
        raise FileExistsError(f"Refusing to overwrite temporary path: {temp_path}")

    backup_path = None
    try:
        with conn:  # for the dashboard's before/after sizes (hook-triggered jobs arrive without a size)
            conn.execute("UPDATE jobs SET source_size=COALESCE(source_size, ?) WHERE id=?",
                         (os.path.getsize(input_path), job_id))
        video_info = legacy.probe_video_info(input_path)
        mode = legacy.hdr_mode(video_info)
        logger.info(
            "Video format: %s path=%s", legacy.describe_video(video_info, mode), input_path
        )
        if (
            mode == legacy.HDR10_PQ
            and video_info.dovi_profile == 7
            and video_info.dovi_el_present
        ):
            logger.warning(
                "Dolby Vision profile 7 enhancement layer will not be retained; "
                "encoding its HDR10 base layer: %s",
                input_path,
            )

        # wanted text subtitles become .srt files next to the output (not embedded), from the same ffmpeg pass
        subtitles = legacy.subtitle_extractions(input_path)
        subtitle_args, subtitle_temps = legacy.subtitle_output_args(subtitles, temp_path)
        # a manual Re-encode (forced job) always encodes; the remux rule only governs automatic jobs
        remux = None if forced else legacy.remux_decision(video_info, mode, input_path)
        steps = job_steps(video_info, mode, remux, subtitles)
        stage = lambda name: set_stage(settings, input_path, steps, name)  # noqa: E731
        stage(steps[0])
        if remux:
            command = with_progress(legacy.build_remux_cmd(input_path, temp_path, video_info, mode) + subtitle_args,
                                    input_path, settings, "remux")
            logger.warning("Remux start (no re-encode: %s): %s", remux, input_path)
            logger.info("Remux cmd: %s (cwd=%s)", legacy.command_text(command), settings.work_dir)
            return_code, command_log = legacy.run(command, settings.work_dir, logger)
            if STOP_REQUESTED:
                raise WorkerStopping()
            if return_code != 0:
                detail = command_log.strip().splitlines()
                raise RuntimeError(f"ffmpeg remux exit {return_code}: {detail[-1] if detail else 'no ffmpeg error text'}")
            if legacy.count_video_frames(temp_path) != legacy.count_video_frames(input_path):
                raise RuntimeError("remux output has a different frame count than the source")
        else:
            encode_video(input_path, temp_path, video_info, mode, subtitle_args, settings, logger, stage)
        stage("Checking output")
        output_info = legacy.validate_output(temp_path, mode, video_info,
                                             expected_codec=video_info.codec_name if remux else None)
        logger.info(
            "Validated output: %s",
            legacy.describe_video(output_info, legacy.hdr_mode(output_info)),
        )
        spec = legacy.output_spec(video_info, mode)
        if not remux and spec.target in ("hdr10plus", "dv81") and video_info.hdr10_plus and not output_info.hdr10_plus:
            logger.warning("HDR10+ metadata was not retained; output is standard HDR10: %s", input_path)
        missing_metadata = []
        if not spec.tonemap:  # SDR output carries no HDR metadata
            if video_info.has_mastering_display and not output_info.has_mastering_display:
                missing_metadata.append("mastering-display")
            if video_info.has_content_light_level and not output_info.has_content_light_level:
                missing_metadata.append("content-light-level")
        if missing_metadata:
            logger.warning(
                "Static HDR metadata was not retained: %s path=%s",
                ", ".join(missing_metadata),
                input_path,
            )

        check_text_extractions(input_path, subtitles, subtitle_temps)
        try:
            current_signature = SourceSignature.from_path(input_path)
        except OSError:
            current_signature = None
        if current_signature != start_signature:
            raise SourceChangedError("source changed during conversion")

        stage("Installing")
        backup_path = legacy.install_output(input_path, temp_path, output_path)
        output_signature = SourceSignature.from_path(output_path)
        try:
            with conn:
                upsert_file(
                    conn,
                    output_path,
                    output_signature,
                    status="ok",
                    note=(f"remuxed-{video_info.codec_name}-{mode}" if remux
                          else f"encoded-{legacy.output_codec(mode, video_info)}-"
                               f"{legacy.output_spec(video_info, mode).tag_mode}"),
                    owner=owner,
                )
                if output_path != input_path:
                    conn.execute("DELETE FROM files WHERE path=?", (input_path,))
                if owner is not None:
                    enqueue_callback(
                        conn,
                        owner,
                        time.time() + settings.callback_delay_seconds,
                    )
        except Exception:
            rollback_installed_output(
                legacy, input_path, output_path, backup_path, logger
            )
            backup_path = None
            raise

        if subtitles:
            stage("Subtitles")
        installed = place_subtitles(output_path, subtitle_temps, settings, logger)
        if subtitles:
            logger.info("Subtitles extracted: %d of %d (%s): %s", installed, len(subtitles),
                        ", ".join(s.suffix for s in subtitles), output_path)
        if legacy.DELETE:
            try:
                os.remove(backup_path)
            except OSError as error:
                logger.warning("Could not delete original backup %s: %s", backup_path, error)
        else:
            logger.info("Original retained at: %s", backup_path)
        backup_path = None
        finish_job(conn, job_id, output_path=output_path)
        logger.info("%s success: %s -> %s", "Remux" if remux else "Encoding", input_path, output_path)
        jellyfin_media_updated(settings, [output_path], logger,
                               deleted=[input_path] if output_path != input_path else [])
    except SourceChangedError:
        legacy.cleanup_temp(temp_path, logger)
        _remove_temps(locals().get("subtitle_temps"))
        try:
            current = SourceSignature.from_path(input_path)
        except OSError:
            current = None
        requeue_stale_job(conn, job_id, current)
        logger.warning("Source changed during conversion; job requeued: %s", input_path)
    except WorkerStopping:
        legacy.cleanup_temp(temp_path, logger)
        _remove_temps(locals().get("subtitle_temps"))
        with conn:
            conn.execute(
                "UPDATE jobs SET state='queued', available_at=?, started_at=NULL WHERE id=?",
                (time.time(), job_id),
            )
        raise
    except Exception as error:
        legacy.cleanup_temp(temp_path, logger)
        _remove_temps(locals().get("subtitle_temps"))
        try:
            if os.path.isfile(input_path):
                signature = SourceSignature.from_path(input_path)
                with conn:
                    upsert_file(
                        conn,
                        input_path,
                        signature,
                        status="error",
                        note=str(error),
                        owner=owner,
                    )
        except Exception:
            logger.debug("Could not record file error", exc_info=True)
        state = fail_job(conn, job_id, str(error), settings)
        logger.exception("Conversion job=%d %s path=%s: %s", job_id, state, input_path, error)


def submit_rescan(
    row: sqlite3.Row,
    settings: Settings,
) -> Optional[int]:
    instance = settings.instance(str(row["arr_instance"]))
    kind = str(row["arr_kind"])
    if kind == "series" and instance.kind == "sonarr":
        payload = {"name": "RescanSeries", "seriesId": int(row["arr_entity_id"])}
    elif kind == "movie" and instance.kind == "radarr":
        payload = {"name": "RescanMovie", "movieId": int(row["arr_entity_id"])}
    else:
        raise ConfigurationError(
            f"Callback kind {kind!r} does not match instance {instance.name}"
        )
    response = api_request(instance, "POST", "/api/v3/command", settings, payload)
    if isinstance(response, dict) and response.get("id") is not None:
        return int(response["id"])
    return None


def process_callback(
    conn: sqlite3.Connection,
    row: sqlite3.Row,
    settings: Settings,
    logger: logging.Logger,
) -> None:
    key = (row["arr_instance"], row["arr_kind"], row["arr_entity_id"])
    claimed = int(row["claimed_generation"])
    try:
        command_id = submit_rescan(row, settings)
    except Exception as error:
        attempts = int(row["attempts"]) + 1
        with conn:
            conn.execute(
                """
                UPDATE callbacks
                SET state='retry_wait', attempts=?, available_at=?,
                    claimed_generation=NULL, last_error=?, updated_at=?
                WHERE arr_instance=? AND arr_kind=? AND arr_entity_id=?
                """,
                (
                    attempts,
                    time.time() + retry_delay(settings, attempts),
                    str(error),
                    time.time(),
                    *key,
                ),
            )
        logger.error("Callback failed for %s/%s/%s: %s", *key, error)
        return

    with conn:
        current = conn.execute(
            """
            SELECT generation FROM callbacks
            WHERE arr_instance=? AND arr_kind=? AND arr_entity_id=?
            """,
            key,
        ).fetchone()
        if current is None:
            return
        if int(current["generation"]) == claimed:
            state = CALLBACK_DONE
            due = time.time()
        else:
            state = CALLBACK_QUEUED
            due = time.time() + settings.callback_delay_seconds
        conn.execute(
            """
            UPDATE callbacks
            SET state=?, completed_generation=?, claimed_generation=NULL,
                available_at=?, attempts=0, updated_at=?, last_error=NULL,
                last_command_id=?
            WHERE arr_instance=? AND arr_kind=? AND arr_entity_id=?
            """,
            (state, claimed, due, time.time(), command_id, *key),
        )
    logger.info("Submitted %s rescan id=%s command=%s", key[1], key[2], command_id)


def request_worker_stop(signum: int, _frame: object) -> None:
    global STOP_REQUESTED
    STOP_REQUESTED = True
    legacy = _legacy_converter
    process = getattr(legacy, "_active_process", None) if legacy is not None else None
    if process is not None and process.poll() is None:
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass


def acquire_worker_lock(path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    handle = open(path, "a+")
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except Exception:
        handle.close()
        raise
    return handle


class GpuLock:
    """Advisory lock shared with other GPU users (for example subtitlerr's models), so their jobs take turns instead of
    overlapping on the GPU. Path from the GPU_LOCK environment variable; unset means no locking. The worker only tries
    the lock: while another user holds it, conversions wait in the queue and hook events and callbacks still run."""

    def __init__(self, path: Optional[str]):
        self.path = path or None
        self.fd: Optional[int] = None

    def try_acquire(self) -> bool:
        if not self.path:
            return True
        if self.fd is None:
            try:
                self.fd = os.open(self.path, os.O_RDWR | os.O_CREAT, 0o664)
            except PermissionError:  # flock needs no write access to an existing file
                self.fd = os.open(self.path, os.O_RDONLY)
        try:
            fcntl.flock(self.fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            return True
        except BlockingIOError:
            return False

    def release(self) -> None:
        if self.path and self.fd is not None:
            fcntl.flock(self.fd, fcntl.LOCK_UN)


def remove_stale_work_files(settings: Settings, logger: logging.Logger) -> None:
    """At worker start nothing is running (the worker lock is held): temporary encodes, subtitle temporaries and
    injection folders left by an interrupted job are removed, and the progress note."""
    removed = 0
    for path in glob.glob(os.path.join(glob.escape(settings.work_dir), "temp.converterr.*")) + \
            glob.glob(os.path.join(glob.escape(settings.work_dir), "hdr10plus.*")) + \
            glob.glob(os.path.join(glob.escape(settings.work_dir), "dovi.*")) + \
            [os.path.join(settings.work_dir, PROGRESS_FILE), os.path.join(settings.work_dir, PROGRESS_META)]:
        try:
            if os.path.isdir(path):
                shutil.rmtree(path)
            elif os.path.exists(path):
                os.remove(path)
            else:
                continue
            removed += 1
        except OSError as error:
            logger.warning("Could not remove leftover %s: %s", path, error)
    if removed:
        logger.info("Removed %d leftover work file(s) of an interrupted job", removed)


def refresh_capabilities(conn: sqlite3.Connection, logger: logging.Logger, *, force: bool = False) -> dict:
    """Run the hardware/encoder check when it was never run or ffmpeg or the devices changed; store and apply it."""
    import encoders
    current = settings_store.get(conn, "capabilities")
    if force or encoders.stale(current):
        logger.info("Checking encoders and hardware")
        current = encoders.detect()
        settings_store.put(conn, "capabilities", current)
        working = [f"{r['backend']}/{r['codec']}{'' if r['codec'] == 'av1' else '-10bit' if r['ten_bit'] else '-8bit'}"
                   for r in current["results"] if r["ok"]]
        logger.info("Encoders that work here: %s", ", ".join(working) or "none")
    get_legacy_converter().apply_capabilities(current)
    return current


def run_worker(
    conn: sqlite3.Connection,
    settings: Settings,
    logger: logging.Logger,
    *,
    once: bool = False,
    reload: Optional[Callable[[], Settings]] = None,
) -> int:
    global STOP_REQUESTED
    STOP_REQUESTED = False
    signal.signal(signal.SIGINT, request_worker_stop)
    signal.signal(signal.SIGTERM, request_worker_stop)
    recover_interrupted_work(conn)
    recover_spool_events(settings, logger)
    catalog = build_ownership_catalog(settings, logger)
    catalog_loaded = time.monotonic()
    units_processed = 0
    gpu = GpuLock(os.environ.get("GPU_LOCK"))
    waiting_for_gpu = False

    remove_stale_work_files(settings, logger)
    refresh_capabilities(conn, logger)
    settings_version = settings_store.version(conn)
    while not STOP_REQUESTED:
        if reload is not None and settings_store.version(conn) != settings_version:
            settings_version = settings_store.version(conn)
            try:
                settings = reload()
                catalog = build_ownership_catalog(settings, logger)
                catalog_loaded = time.monotonic()
                logger.info("Settings changed; reloaded")
            except ConfigurationError as error:
                logger.error("Saved settings are invalid; keeping the previous ones: %s", error)
        if process_next_spool_event(settings, logger):
            units_processed += 1
            continue

        if process_next_hook_event(conn, settings, logger):
            units_processed += 1
            continue

        callback = claim_callback(conn)
        if callback is not None:
            process_callback(conn, callback, settings, logger)
            units_processed += 1
            continue

        job = None
        if gpu.try_acquire():
            if waiting_for_gpu:
                logger.info("GPU lock acquired")
                waiting_for_gpu = False
            job = claim_job(conn)
            if job is None:
                gpu.release()
        elif not waiting_for_gpu and has_due_job(conn):
            logger.info("Waiting for the GPU lock (%s)", gpu.path)
            waiting_for_gpu = True
        if job is not None:
            if time.monotonic() - catalog_loaded > 3600:
                catalog = build_ownership_catalog(settings, logger)
                catalog_loaded = time.monotonic()
            try:
                process_conversion_job(conn, job, settings, catalog, logger)
            except WorkerStopping:
                break
            finally:
                gpu.release()
            units_processed += 1
            continue

        if once:
            break
        time.sleep(settings.poll_seconds)

    logger.info("Worker stopped; queue units processed=%d", units_processed)
    return 0


INTERVAL_PATTERN = re.compile(r"^[1-9][0-9]*(?:us|ms|s|min|h|d|w)$")


def validate_scan_interval(value: str) -> str:
    if not INTERVAL_PATTERN.fullmatch(value):
        raise ConfigurationError(
            "scan interval must be an integer followed by us, ms, s, min, h, d, or w"
        )
    return value


@dataclass(frozen=True)
class ServiceIdentity:
    user: str
    group: str
    uid: int
    gid: int


def resolve_service_identity(
    user: Optional[str],
    group: Optional[str],
    *,
    script_path: str,
    allow_root: bool,
) -> ServiceIdentity:
    if (user is None) != (group is None):
        raise ConfigurationError("--user and --group must be supplied together")
    if user is None:
        stat_result = os.stat(script_path)
        try:
            user_entry = pwd.getpwuid(stat_result.st_uid)
            group_entry = grp.getgrgid(stat_result.st_gid)
        except KeyError as error:
            raise ConfigurationError("Script owner/group cannot be resolved") from error
    else:
        try:
            user_entry = pwd.getpwnam(user)
            group_entry = grp.getgrnam(group)
        except KeyError as error:
            raise ConfigurationError(f"Unknown service user/group: {error}") from error
    identity = ServiceIdentity(
        user=user_entry.pw_name,
        group=group_entry.gr_name,
        uid=user_entry.pw_uid,
        gid=group_entry.gr_gid,
    )
    if identity.uid == 0 and not allow_root:
        raise ConfigurationError(
            "Refusing to install the worker as root; pass --user/--group or --allow-root"
        )
    return identity


def _identity_groups(identity: ServiceIdentity) -> set[int]:
    try:
        return set(os.getgrouplist(identity.user, identity.gid))
    except OSError:
        return {identity.gid}


def identity_has_access(path: str, identity: ServiceIdentity, mask: int) -> bool:
    stat_result = os.stat(path)
    mode = stat_result.st_mode
    if identity.uid == 0:
        return True
    if stat_result.st_uid == identity.uid:
        bits = (mode >> 6) & 0b111
    elif stat_result.st_gid in _identity_groups(identity):
        bits = (mode >> 3) & 0b111
    else:
        bits = mode & 0b111
    return bits & mask == mask


def validate_service_access(
    settings: Settings,
    identity: ServiceIdentity,
) -> list[str]:
    warnings: list[str] = []
    checks = [
        (os.path.dirname(settings.database_path), 0b011, "state directory (write/execute)"),
        (settings.work_dir, 0b011, "work directory (write/execute)"),
        (settings.hook_spool_dir, 0b011, "hook spool directory (write/execute)"),
    ]
    checks.extend((root, 0b101, "scan root (read/execute)") for root in settings.scan_roots)
    render_device = "/dev/dri/renderD128"
    if os.path.exists(render_device):
        checks.append((render_device, 0b110, "GPU render device (read/write)"))
    for path, mask, description in checks:
        try:
            if not identity_has_access(path, identity, mask):
                warnings.append(f"{identity.user}:{identity.group} may not access {description}: {path}")
        except OSError as error:
            warnings.append(f"Cannot validate {description} {path}: {error}")
    return warnings


def systemd_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_systemd_units(
    script_path: str,
    python_path: str,
    config_path: str,
    identity: ServiceIdentity,
    interval: str,
) -> dict[str, str]:
    interval = validate_scan_interval(interval)
    base_command = " ".join(
        systemd_quote(item)
        for item in (python_path, script_path, "--config", config_path)
    )
    common_service = f"""{UNIT_MARKER}
[Unit]
Wants=network-online.target
After=network-online.target

[Service]
User={identity.user}
Group={identity.group}
UMask=0002
WorkingDirectory={os.path.dirname(script_path)}
"""
    worker = common_service + f"""Type=simple
ExecStart={base_command} worker
Restart=on-failure
RestartSec=10s
KillMode=control-group
TimeoutStopSec=90s

[Install]
WantedBy=multi-user.target
"""
    scan = common_service + f"""Type=oneshot
ExecStart={base_command} scan
Nice=10
IOSchedulingClass=idle
"""
    timer = f"""{UNIT_MARKER}
[Unit]
Description=Periodic media_converterr full library scan

[Timer]
OnBootSec=15min
OnUnitInactiveSec={interval}
Unit=media-converterr-scan.service

[Install]
WantedBy=timers.target
"""
    return {
        "media-converterr-worker.service": worker,
        "media-converterr-scan.service": scan,
        "media-converterr-scan.timer": timer,
    }


def write_generated_unit(path: str, content: str) -> None:
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            first_line = handle.readline().rstrip("\n")
        if first_line != UNIT_MARKER:
            raise RuntimeError(f"Refusing to overwrite non-media_converterr unit: {path}")
    temporary = f"{path}.tmp.{os.getpid()}"
    try:
        with open(temporary, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def run_systemctl(arguments: Sequence[str], *, check: bool = True) -> None:
    subprocess.run(["systemctl", *arguments], check=check)


def install_systemd(
    settings: Settings,
    config_path: str,
    interval: str,
    user: Optional[str],
    group: Optional[str],
    allow_root: bool,
    *,
    unit_dir: str = "/etc/systemd/system",
) -> ServiceIdentity:
    if os.geteuid() != 0:
        raise PermissionError("systemd installation must be run as root")
    script_path = os.path.realpath(__file__)
    identity = resolve_service_identity(
        user,
        group,
        script_path=script_path,
        allow_root=allow_root,
    )
    interval = validate_scan_interval(interval)
    created = initialize_database(settings)
    if created:
        os.chown(settings.database_path, identity.uid, identity.gid)
    units = render_systemd_units(
        script_path,
        os.path.realpath(sys.executable),
        os.path.realpath(config_path),
        identity,
        interval,
    )
    os.makedirs(unit_dir, exist_ok=True)
    for name, content in units.items():
        write_generated_unit(os.path.join(unit_dir, name), content)
    run_systemctl(["daemon-reload"])
    run_systemctl(["enable", "--now", "media-converterr-worker.service"])
    run_systemctl(["enable", "--now", "media-converterr-scan.timer"])
    return identity


def remove_systemd(*, unit_dir: str = "/etc/systemd/system") -> list[str]:
    if os.geteuid() != 0:
        raise PermissionError("systemd removal must be run as root")
    run_systemctl(
        [
            "disable",
            "--now",
            "media-converterr-scan.timer",
            "media-converterr-worker.service",
        ],
        check=False,
    )
    run_systemctl(["stop", "media-converterr-scan.service"], check=False)
    removed = []
    for name in UNIT_NAMES:
        path = os.path.join(unit_dir, name)
        if not os.path.exists(path):
            continue
        with open(path, "r", encoding="utf-8") as handle:
            first_line = handle.readline().rstrip("\n")
        if first_line != UNIT_MARKER:
            raise RuntimeError(f"Refusing to remove non-media_converterr unit: {path}")
        os.unlink(path)
        removed.append(path)
    run_systemctl(["daemon-reload"])
    run_systemctl(["reset-failed"], check=False)
    return removed


def status_snapshot(conn: sqlite3.Connection) -> dict[str, Any]:
    jobs = {
        row["state"]: row["count"]
        for row in conn.execute("SELECT state, COUNT(*) AS count FROM jobs GROUP BY state")
    }
    callbacks = {
        row["state"]: row["count"]
        for row in conn.execute(
            "SELECT state, COUNT(*) AS count FROM callbacks GROUP BY state"
        )
    }
    hooks = {
        row["state"]: row["count"]
        for row in conn.execute(
            "SELECT state, COUNT(*) AS count FROM hook_events GROUP BY state"
        )
    }
    failures = [
        dict(row)
        for row in conn.execute(
            """
            SELECT id, path, attempts, last_error FROM jobs
            WHERE state='failed' ORDER BY finished_at DESC, id DESC LIMIT 20
            """
        )
    ]
    return {"jobs": jobs, "callbacks": callbacks, "hooks": hooks, "failures": failures}


def retry_job(conn: sqlite3.Connection, job_id: int) -> bool:
    with conn:
        updated = conn.execute(
            """
            UPDATE jobs SET state='queued', attempts=0, available_at=?,
                            finished_at=NULL, last_error=NULL
            WHERE id=? AND state IN ('failed', 'cancelled')
            """,
            (time.time(), job_id),
        ).rowcount
    return updated == 1


