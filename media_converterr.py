def collect_scan_paths(
    settings: Settings,
    logger: logging.Logger,
) -> tuple[list[str], list[tuple[str, tuple[int, int]]]]:
    paths: list[str] = []
    completed: list[tuple[str, tuple[int, int]]] = []
    for base_path in settings.scan_roots:
        logger.info("Scanning %s", base_path)
        started = time.time()
        try:
            root_stat = os.stat(base_path)
        except OSError as error:
            logger.warning(
                "Scan unavailable; orphan cleanup disabled for %s: %s",
                base_path,
                error,
            )
            continue
        if not os.path.isdir(base_path):
            logger.warning("Scan path is not a directory: %s", base_path)
            continue

        scan_errors: list[OSError] = []

        def record_error(error: OSError) -> None:
            scan_errors.append(error)
            logger.warning("Scan error for %s: %s", base_path, error)

        for root, dirs, files in os.walk(base_path, topdown=True, onerror=record_error):
            dirs[:] = [name for name in dirs if name not in settings.exclude]
            for filename in files:
                extension = filename.rsplit(".", 1)[-1].lower()
                if extension in settings.convertible_extensions and not filename.startswith("."):  # hidden = temp files
                    paths.append(normalize_path(os.path.join(root, filename)))
        if scan_errors:
            logger.warning("Incomplete scan; orphan cleanup disabled for %s", base_path)
        else:
            completed.append((base_path, (root_stat.st_dev, root_stat.st_ino)))
        logger.info("Scan time %.0fs for %s", time.time() - started, base_path)
    return list(dict.fromkeys(paths)), completed


def removable_orphans(
    conn: sqlite3.Connection,
    completed_roots: Sequence[str],
    paths_seen_at_scan: set[str],
) -> list[str]:
    roots = [normalize_path(root) for root in completed_roots]
    initial_paths = {normalize_path(path) for path in paths_seen_at_scan}
    orphaned: list[str] = []
    for row in conn.execute("SELECT path, device FROM files"):
        path = normalize_path(row["path"])
        matching_root = next((root for root in roots if path_is_within(path, root)), None)
        if matching_root is None or os.path.exists(path) or path in initial_paths:
            continue

        stored_device = row["device"]
        if stored_device is not None:
            ancestor = os.path.dirname(path)
            ancestor_device = None
            while path_is_within(ancestor, matching_root):
                try:
                    ancestor_device = os.stat(ancestor).st_dev
                    break
                except (FileNotFoundError, NotADirectoryError):
                    parent = os.path.dirname(ancestor)
                    if parent == ancestor:
                        break
                    ancestor = parent
                except OSError:
                    break
            if ancestor_device != stored_device:
                continue
        orphaned.append(path)
    return orphaned


def verified_cleanup_roots(
    completed: Sequence[tuple[str, tuple[int, int]]],
    logger: logging.Logger,
) -> list[str]:
    roots = []
    for root, initial_identity in completed:
        try:
            current = os.stat(root)
        except OSError as error:
            logger.warning(
                "Scan path unavailable after scan; orphan cleanup disabled for %s: %s",
                root,
                error,
            )
            continue
        if (current.st_dev, current.st_ino) != initial_identity:
            logger.warning("Scan path identity changed; cleanup disabled for %s", root)
            continue
        roots.append(root)
    return roots


def scan_libraries(
    conn: sqlite3.Connection,
    settings: Settings,
    logger: logging.Logger,
    *,
    dry_run: bool = False,
) -> dict[str, int]:
    catalog = build_ownership_catalog(settings, logger)
    paths, completed = collect_scan_paths(settings, logger)
    summary = {
        "found": len(paths),
        "queued": 0,
        "unchanged": 0,
        "renamed": 0,
        "orphaned": 0,
        "own_output": 0,
        "failed": 0,
    }
    logger.info("Candidates found: %d", len(paths))
    for path in paths:
        if not dry_run:
            retire_european_portuguese(path, settings, logger)
            record_sidecar_inventory(settings.database_path, path)
        try:
            signature = SourceSignature.from_path(path)
            row = get_file_row(conn, path)
            stored_owner = owner_from_row(row)
            owner = choose_owner(path, settings, catalog, stored_owner)
            verified = lookup_verified_file(conn, path, signature) if not dry_run else (
                row
                if row is not None
                and row["size"] == signature.size
                and row["mtime"] == signature.mtime
                and row["status"] == "ok"
                else None
            )
            renamed_from = None
            if verified is None and not dry_run:
                renamed_from = reconcile_rename(conn, path, signature)
                if renamed_from:
                    summary["renamed"] += 1
                    verified = lookup_verified_file(conn, path, signature)
                    if owner is None:
                        owner = stored_owner_for_path(conn, path)
            if verified is not None:
                summary["unchanged"] += 1
                if not dry_run:
                    update_file_owner(conn, path, owner)
                continue
            own = converter_output(conn, path, signature)
            if own:
                summary["own_output"] += 1
                logger.info("Skip (converter output, %s; re-encode only on request): %s", own, path)
                if not dry_run:
                    refresh_own_output(conn, path, signature, owner, own)
                continue
            summary["queued"] += 1
            if not dry_run:
                enqueue_job(
                    conn,
                    path,
                    trigger="scan",
                    event_type="WeeklyScan",
                    owner=owner,
                    signature=signature,
                )
        except OSError as error:
            summary["failed"] += 1
            logger.warning("Could not inspect scan candidate %s: %s", path, error)
        except Exception as error:
            summary["failed"] += 1
            logger.exception("Could not reconcile scan candidate %s: %s", path, error)

    cleanup_roots = verified_cleanup_roots(completed, logger)
    orphaned = removable_orphans(conn, cleanup_roots, set(paths))
    summary["orphaned"] = len(orphaned)
    if orphaned and not dry_run:
        with conn:
            conn.executemany("DELETE FROM files WHERE path=?", ((path,) for path in orphaned))
            for path in orphaned:
                conn.execute(
                    """
                    UPDATE jobs SET state='cancelled', finished_at=?,
                                    last_error='file missing after verified scan'
                    WHERE path=? AND state IN ('queued', 'retry_wait')
                    """,
                    (time.time(), path),
                )
    logger.info(
        "Scan summary: found=%d queued=%d unchanged=%d renamed=%d orphaned=%d own_output=%d failed=%d%s",
        summary["found"],
        summary["queued"],
        summary["unchanged"],
        summary["renamed"],
        summary["orphaned"],
        summary["own_output"],
        summary["failed"],
        " dry-run" if dry_run else "",
    )
    return summary


