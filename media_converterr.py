def api_request(
    instance: ArrInstance,
    method: str,
    endpoint: str,
    settings: Settings,
    payload: Optional[Mapping[str, Any]] = None,
) -> Any:
    if not instance.url or not instance.api_key:
        raise ConfigurationError(f"API URL/key not configured for {instance.name}")
    data = None if payload is None else json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        f"{instance.url}{endpoint}",
        data=data,
        method=method,
        headers={
            "X-Api-Key": instance.api_key,
            "Accept": "application/json",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=settings.api_timeout_seconds) as response:
            body = response.read()
    except urllib.error.HTTPError as error:
        detail = error.read().decode("utf-8", "replace")[:500]
        raise RuntimeError(
            f"{instance.name} API returned HTTP {error.code}: {detail}"
        ) from error
    except urllib.error.URLError as error:
        raise RuntimeError(f"{instance.name} API request failed: {error.reason}") from error
    if not body:
        return None
    try:
        return json.loads(body)
    except json.JSONDecodeError as error:
        raise RuntimeError(f"{instance.name} returned invalid JSON") from error


def build_ownership_catalog(settings: Settings, logger: logging.Logger) -> OwnershipCatalog:
    entries: list[CatalogEntry] = []
    unavailable: set[str] = set()
    for instance in settings.instances:
        endpoint = "/api/v3/series" if instance.kind == "sonarr" else "/api/v3/movie"
        try:
            response = api_request(instance, "GET", endpoint, settings)
            if not isinstance(response, list):
                raise RuntimeError("catalogue response is not a list")
            for entity in response:
                if not isinstance(entity, dict) or "id" not in entity or "path" not in entity:
                    continue
                try:
                    local_path = translate_remote_path(str(entity["path"]), instance)
                    entity_id = int(entity["id"])
                except (ConfigurationError, TypeError, ValueError) as error:
                    logger.warning("Ignoring invalid %s catalogue item: %s", instance.name, error)
                    continue
                entries.append(
                    CatalogEntry(
                        path=local_path,
                        owner=Ownership(instance.name, instance.entity_kind, entity_id),
                    )
                )
        except Exception as error:
            unavailable.add(instance.name)
            logger.warning("Could not load %s catalogue: %s", instance.name, error)
    return OwnershipCatalog(entries, unavailable, logger)


def is_explicitly_unlinked(path: str, settings: Settings) -> bool:
    return any(path_is_within(path, root) for root in settings.unlinked_folders)


def choose_owner(
    path: str,
    settings: Settings,
    catalog: OwnershipCatalog,
    stored: Optional[Ownership] = None,
) -> Optional[Ownership]:
    if is_explicitly_unlinked(path, settings):
        return None
    owner = catalog.owner_for_path(path)
    if owner is not None:
        return owner
    if stored is not None and stored.instance in catalog.unavailable_instances:
        return stored
    return stored if stored is not None and not catalog.entries else None


def capture_hook_event(
    database_path: str,
    instance_name: Optional[str],
    environ: Mapping[str, str],
) -> Optional[int]:
    arr_type = "sonarr" if "sonarr_eventtype" in environ else None
    if arr_type is None and "radarr_eventtype" in environ:
        arr_type = "radarr"
    if arr_type is None:
        raise RuntimeError("No Sonarr or Radarr event variables were provided")
    event_type = environ[f"{arr_type}_eventtype"]
    if event_type.lower() == "test":
        return None
    instance = instance_name or environ.get("MEDIA_CONVERTERR_INSTANCE") or arr_type
    prefix = arr_type + "_"
    payload = {
        key.lower(): value
        for key, value in environ.items()
        if key.lower().startswith(prefix)
    }
    now = time.time()
    conn = require_hook_database(database_path)
    try:
        with conn:
            cursor = conn.execute(
                """
                INSERT INTO hook_events(
                    arr_instance, arr_type, event_type, payload,
                    state, available_at, created_at
                ) VALUES(?,?,?,?,'queued',?,?)
                """,
                (instance, arr_type, event_type, json.dumps(payload), now, now),
            )
        return int(cursor.lastrowid)
    finally:
        conn.close()


def webhook_environ(arr_type: str, body: Mapping[str, Any]) -> dict[str, str]:
    """A Sonarr/Radarr Webhook payload (JSON) as the variables their Custom Script would get, so both routes share
    process_hook_event. Covers the fields it reads: event type, series/movie id and folder, file path(s), previous
    paths of a rename and the deleted-files flag of a series/movie delete."""
    if arr_type not in {"sonarr", "radarr"}:
        raise ValueError(f"Unknown *arr type: {arr_type!r}")
    p = arr_type + "_"
    entity_name, file_name = ("series", "episodefile") if arr_type == "sonarr" else ("movie", "moviefile")
    entity = body.get("series" if arr_type == "sonarr" else "movie") or {}
    environ = {p + "eventtype": str(body.get("eventType", ""))}
    if entity.get("id") is not None:
        environ[f"{p}{entity_name}_id"] = str(entity["id"])
    folder = entity.get("path") or entity.get("folderPath")
    if folder:
        environ[f"{p}{entity_name}_path"] = str(folder)
    single = body.get("episodeFile" if arr_type == "sonarr" else "movieFile") or {}
    many = body.get("episodeFiles" if arr_type == "sonarr" else "movieFiles") or []
    renamed = body.get("renamedEpisodeFiles" if arr_type == "sonarr" else "renamedMovieFiles") or []
    paths = [str(item["path"]) for item in [single, *many, *renamed] if isinstance(item, dict) and item.get("path")]
    paths = list(dict.fromkeys(paths))
    if paths:
        environ[f"{p}{file_name}_path"] = paths[0]
        environ[f"{p}{file_name}_paths"] = "|".join(paths)
    previous = [str(item.get("previousPath") or "") for item in renamed if isinstance(item, dict)]
    if any(previous):
        environ[f"{p}{file_name}_previouspaths"] = "|".join(previous)
    if "deletedFiles" in body and isinstance(body["deletedFiles"], bool):
        environ[f"{p}{entity_name}_deletedfiles"] = str(body["deletedFiles"])
    return environ


def parse_environment_lines(lines: Iterable[str]) -> dict[str, str]:
    environ: dict[str, str] = {}
    for line in lines:
        line = line.rstrip("\n")
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        if key:
            environ[key] = value
    return environ


def recover_spool_events(settings: Settings, logger: logging.Logger) -> None:
    spool = Path(settings.hook_spool_dir)
    if not spool.exists():
        return
    for path in sorted(spool.glob("*.event.processing")):
        event_path = path.with_name(path.name.removesuffix(".processing"))
        if event_path.exists():
            logger.warning("Leaving duplicate processing hook event in place: %s", path)
            continue
        try:
            os.replace(path, event_path)
        except OSError as error:
            logger.warning("Could not recover spool event %s: %s", path, error)


def process_next_spool_event(settings: Settings, logger: logging.Logger) -> bool:
    spool = Path(settings.hook_spool_dir)
    try:
        os.makedirs(spool, exist_ok=True)
    except OSError as error:
        logger.warning("Hook spool unavailable: %s", error)
        return False

    for event_path in sorted(spool.glob("*.event")):
        processing_path = event_path.with_name(event_path.name + ".processing")
        try:
            os.replace(event_path, processing_path)
        except FileNotFoundError:
            continue
        except OSError as error:
            logger.warning("Could not claim spool event %s: %s", event_path, error)
            continue

        try:
            with open(processing_path, "r", encoding="utf-8", errors="replace") as handle:
                environ = parse_environment_lines(handle)
            event_id = capture_hook_event(
                settings.database_path,
                environ.get("MEDIA_CONVERTERR_INSTANCE"),
                environ,
            )
            os.unlink(processing_path)
        except Exception as error:
            failed_path = processing_path.with_name(
                f"{processing_path.name}.failed.{int(time.time())}"
            )
            try:
                os.replace(processing_path, failed_path)
            except OSError:
                pass
            logger.exception("Spool hook event failed: %s", event_path)
        else:
            if event_id is None:
                logger.info("Processed spool hook test: %s", event_path.name)
            else:
                logger.info("Queued spool hook event %d from %s", event_id, event_path.name)
        return True
    return False


def split_paths(value: Optional[str]) -> list[str]:
    if not value:
        return []
    return [item for item in value.split("|") if item]


def payload_int(payload: Mapping[str, str], key: str) -> Optional[int]:
    try:
        return int(payload[key])
    except (KeyError, TypeError, ValueError):
        return None


def event_paths(payload: Mapping[str, str], singular: str, plural: str) -> list[str]:
    result = split_paths(payload.get(plural))
    if not result and payload.get(singular):
        result = [payload[singular]]
    return list(dict.fromkeys(result))


def process_hook_event(
    conn: sqlite3.Connection,
    row: sqlite3.Row,
    settings: Settings,
    logger: logging.Logger,
) -> None:
    instance = settings.instance(str(row["arr_instance"]))
    arr_type = str(row["arr_type"])
    if instance.kind != arr_type:
        raise ConfigurationError(
            f"Hook type {arr_type} does not match instance {instance.name} ({instance.kind})"
        )
    payload = json.loads(row["payload"])
    event_type = str(row["event_type"])
    lower_event = event_type.lower()

    if arr_type == "sonarr":
        entity_id = payload_int(payload, "sonarr_series_id")
        owner = Ownership(instance.name, "series", entity_id) if entity_id is not None else None
        current = event_paths(
            payload, "sonarr_episodefile_path", "sonarr_episodefile_paths"
        )
        previous = split_paths(payload.get("sonarr_episodefile_previouspaths"))
        entity_path = payload.get("sonarr_series_path")
        file_delete = lower_event == "episodefiledelete"
        entity_delete = lower_event == "seriesdelete"
        deleted_files = str(payload.get("sonarr_series_deletedfiles", "false")).lower() == "true"
    else:
        entity_id = payload_int(payload, "radarr_movie_id")
        owner = Ownership(instance.name, "movie", entity_id) if entity_id is not None else None
        current = event_paths(
            payload, "radarr_moviefile_path", "radarr_moviefile_paths"
        )
        previous = split_paths(payload.get("radarr_moviefile_previouspaths"))
        entity_path = payload.get("radarr_movie_path")
        file_delete = lower_event == "moviefiledelete"
        entity_delete = lower_event == "moviedelete"
        deleted_files = str(payload.get("radarr_movie_deletedfiles", "false")).lower() == "true"

    if file_delete:
        for raw_path in current:
            path = translate_remote_path(raw_path, instance)
            with conn:
                conn.execute("DELETE FROM files WHERE path=?", (path,))
                conn.execute(
                    """
                    UPDATE jobs SET state='cancelled', finished_at=?,
                                    last_error='deleted by *arr event'
                    WHERE path=? AND state IN ('queued', 'retry_wait')
                    """,
                    (time.time(), path),
                )
        logger.info("Processed %s delete event paths=%d", instance.name, len(current))
        return

    if entity_delete and entity_path:
        local_entity_path = translate_remote_path(entity_path, instance)
        rows = conn.execute("SELECT path FROM files").fetchall()
        affected = [item["path"] for item in rows if path_is_within(item["path"], local_entity_path)]
        with conn:
            if deleted_files:
                conn.executemany("DELETE FROM files WHERE path=?", ((path,) for path in affected))
                for path in affected:
                    conn.execute(
                        """
                        UPDATE jobs SET state='cancelled', finished_at=?,
                                        last_error='entity deleted by *arr'
                        WHERE path=? AND state IN ('queued', 'retry_wait')
                        """,
                        (time.time(), path),
                    )
            else:
                conn.executemany(
                    """
                    UPDATE files SET arr_instance=NULL, arr_kind=NULL,
                                     arr_entity_id=NULL, owner_checked_at=?
                    WHERE path=?
                    """,
                    ((time.time(), path) for path in affected),
                )
        logger.info(
            "Processed %s entity delete path=%s files=%d deleted=%s",
            instance.name,
            local_entity_path,
            len(affected),
            deleted_files,
        )
        return

    if lower_event not in {"download", "rename"}:
        logger.info("Ignoring unsupported %s hook event=%s", instance.name, event_type)
        return

    for index, raw_path in enumerate(current):
        path = translate_remote_path(raw_path, instance)
        previous_path = None
        if index < len(previous):
            previous_path = translate_remote_path(previous[index], instance)
        enqueue_job(
            conn,
            path,
            trigger="hook",
            event_type=event_type,
            owner=owner,
            previous_path=previous_path,
            available_at=time.time() + settings.settle_seconds,
        )
    if lower_event == "rename":
        pairs = [(translate_remote_path(p, instance),
                  translate_remote_path(previous[i], instance) if i < len(previous) else None)
                 for i, p in enumerate(current)]
        folder = translate_remote_path(entity_path, instance) if entity_path else None
        repair_after_rename(pairs, settings, logger, folder)
    logger.info("Processed %s %s event paths=%d", instance.name, event_type, len(current))


def process_next_hook_event(
    conn: sqlite3.Connection,
    settings: Settings,
    logger: logging.Logger,
) -> bool:
    now = time.time()
    conn.execute("BEGIN IMMEDIATE")
    try:
        row = conn.execute(
            """
            SELECT * FROM hook_events
            WHERE state IN ('queued', 'retry_wait') AND available_at<=?
            ORDER BY id LIMIT 1
            """,
            (now,),
        ).fetchone()
        if row is None:
            conn.commit()
            return False
        conn.execute("UPDATE hook_events SET state='running' WHERE id=?", (row["id"],))
        conn.commit()
    except Exception:
        conn.rollback()
        raise

    try:
        process_hook_event(conn, row, settings, logger)
    except Exception as error:
        attempts = int(row["attempts"]) + 1
        with conn:
            conn.execute(
                """
                UPDATE hook_events
                SET state='retry_wait', attempts=?, available_at=?, last_error=?
                WHERE id=?
                """,
                (
                    attempts,
                    time.time() + retry_delay(settings, attempts),
                    str(error),
                    row["id"],
                ),
            )
        logger.error("Hook event %s failed: %s", row["id"], error)
    else:
        with conn:
            conn.execute(
                """
                UPDATE hook_events SET state='done', processed_at=?, last_error=NULL
                WHERE id=?
                """,
                (time.time(), row["id"]),
            )
    return True


