def finish_job(
    conn: sqlite3.Connection,
    job_id: int,
    *,
    output_path: Optional[str] = None,
    skipped: bool = False,
) -> None:
    row = conn.execute(
        "SELECT rerun_requested, path FROM jobs WHERE id=?", (job_id,)
    ).fetchone()
    if row is None:
        return
    now = time.time()
    if row["rerun_requested"]:
        next_path = output_path or row["path"]
        with conn:
            conn.execute(
                """
                UPDATE jobs
                SET path=?, previous_path=NULL, state='queued', available_at=?,
                    started_at=NULL, finished_at=NULL, rerun_requested=0,
                    output_path=?, last_error=NULL
                WHERE id=?
                """,
                (next_path, now, output_path, job_id),
            )
    else:
        with conn:
            conn.execute(
                """
                UPDATE jobs
                SET state='done', finished_at=?,
                    output_path=COALESCE(?, output_path), last_error=?
                WHERE id=?
                """,
                (now, output_path, "already verified" if skipped else None, job_id),
            )


