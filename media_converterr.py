def register_webhook(instance: ArrInstance, settings: Settings, url: str) -> str:
    """Create or update this service's Webhook connection in a Sonarr/Radarr instance. The *arr app sends a Test
    event to the URL while saving, so this service must already answer there. Returns "created" or "updated"."""
    existing = [item for item in api_request(instance, "GET", "/api/v3/notification", settings) or []
                if item.get("name") == WEBHOOK_NAME]
    if existing:
        connection = existing[0]
    else:
        schema = [item for item in api_request(instance, "GET", "/api/v3/notification/schema", settings) or []
                  if item.get("implementation") == "Webhook"]
        if not schema:
            raise RuntimeError(f"{instance.name} offers no Webhook connection")
        connection = dict(schema[0])
        connection.pop("id", None)
    connection["name"] = WEBHOOK_NAME
    connection.setdefault("tags", [])
    wanted = WEBHOOK_EVENTS[instance.kind]
    for key, value in list(connection.items()):
        if key.startswith("on") and isinstance(value, bool):
            connection[key] = key in wanted and connection.get("supports" + key[2:], True) is not False
    for field in connection.get("fields", []):
        if field.get("name") == "url":
            field["value"] = url
        elif field.get("name") == "method":
            field["value"] = 1  # POST
    if existing:
        api_request(instance, "PUT", f"/api/v3/notification/{connection['id']}", settings, connection)
        return "updated"
    api_request(instance, "POST", "/api/v3/notification", settings, connection)
    return "created"


def other_hook_connections(instance: ArrInstance, settings: Settings) -> list[str]:
    """Names of other connections that look like they feed this service too (a Custom Script), which would queue
    every event twice once the webhook is registered."""
    names = []
    for item in api_request(instance, "GET", "/api/v3/notification", settings) or []:
        if item.get("name") == WEBHOOK_NAME:
            continue
        values = " ".join(str(f.get("value", "")) for f in item.get("fields", []))
        if item.get("implementation") == "CustomScript" and "media" in values.lower() and "conver" in values.lower():
            names.append(str(item.get("name")))
    return names


def arr_status(instance: ArrInstance, settings: Settings) -> str:
    """One-line connection check for the web interface."""
    status = api_request(instance, "GET", "/api/v3/system/status", settings) or {}
    roots = [str(item.get("path", "")) for item in api_request(instance, "GET", "/api/v3/rootfolder", settings) or []]
    unmapped = [root for root in roots if not path_is_within(root, instance.remote_root)]
    text = f"{status.get('appName', instance.kind)} {status.get('version', '?')}"
    if unmapped:
        text += f"; root folders outside {instance.remote_root}: {', '.join(unmapped)}"
    if not os.path.isdir(instance.local_root):
        text += f"; {instance.local_root} is not visible to this service"
    return text


