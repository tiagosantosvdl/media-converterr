def _api_key_from_file(path: object) -> str:
    """API key from a Sonarr/Radarr config.xml (<ApiKey>), so no key has to be copied into this config."""
    if not path:
        return ""
    try:
        with open(str(path), encoding="utf-8") as handle:
            match = re.search(r"<ApiKey>\s*([^<\s]+)\s*</ApiKey>", handle.read())
    except OSError as error:
        raise ConfigurationError(f"Cannot read api_key_file {path}: {error}") from None
    if not match:
        raise ConfigurationError(f"No <ApiKey> in api_key_file {path}")
    return match.group(1)


def parse_instances(values: object) -> tuple[ArrInstance, ...]:
    """Sonarr/Radarr instances from the TOML [[instances]] tables or the stored connections (same keys)."""
    if not isinstance(values, list):
        raise ConfigurationError("[[instances]] entries are required")
    parsed, names = [], set()
    for raw in values:
        if not isinstance(raw, dict):
            raise ConfigurationError("Each [[instances]] value must be a table")
        name = str(raw.get("name", "")).strip()
        kind = str(raw.get("type", "")).strip().lower()
        if not name or name in names:
            raise ConfigurationError(f"Invalid or duplicate instance name: {name!r}")
        if kind not in {"sonarr", "radarr"}:
            raise ConfigurationError(f"Invalid instance type for {name}: {kind!r}")
        names.add(name)
        parsed.append(ArrInstance(
            name=name,
            kind=kind,
            url=str(raw.get("url", "")).rstrip("/"),
            api_key=str(raw.get("api_key", "")) or _api_key_from_file(raw.get("api_key_file")),
            remote_root=_absolute_config_path(raw.get("remote_root"), f"{name}.remote_root"),
            local_root=_absolute_config_path(raw.get("local_root"), f"{name}.local_root"),
        ))
    return tuple(parsed)


def parse_jellyfin(raw: object) -> Optional[JellyfinSettings]:
    """[jellyfin] table or stored value; None unless both a URL and a key are set."""
    if not isinstance(raw, dict) or not isinstance(raw.get("paths", []), list):
        raise ConfigurationError("[jellyfin] must be a table with a paths array")
    key = str(raw.get("api_key", "")) or os.environ.get(str(raw.get("api_key_env", "JELLYFIN_API_KEY")), "")
    paths = tuple((_absolute_config_path(item.get("local"), "jellyfin.paths.local"),
                   _absolute_config_path(item.get("remote"), "jellyfin.paths.remote"))
                  for item in raw.get("paths", []))
    if raw.get("url") and key:
        return JellyfinSettings(str(raw["url"]).rstrip("/"), key, paths)
    return None


def apply_stored_connections(settings: Settings, stored: object) -> Settings:
    """Connections saved from the web interface replace the file's. A stored instance or Jellyfin entry with an
    empty API key keeps the key the file gives the same name (so keys can stay in config.xml or the environment)."""
    if not isinstance(stored, dict):
        return settings
    changes: dict[str, Any] = {}
    if stored.get("instances"):
        file_keys = {item.name: item.api_key for item in settings.instances}
        changes["instances"] = tuple(
            item if item.api_key else dataclasses.replace(item, api_key=file_keys.get(item.name, ""))
            for item in parse_instances(stored["instances"]))
    if "jellyfin" in stored:
        raw = stored["jellyfin"]
        if raw and not raw.get("api_key") and settings.jellyfin:
            raw = {**raw, "api_key": settings.jellyfin.api_key}
        changes["jellyfin"] = parse_jellyfin(raw) if raw else None
    if stored.get("public_url"):
        changes["public_url"] = str(stored["public_url"]).rstrip("/")
    return dataclasses.replace(settings, **changes)


def _absolute_config_path(value: object, name: str) -> str:
    if not isinstance(value, str) or not os.path.isabs(value):
        raise ConfigurationError(f"{name} must be an absolute path")
    return normalize_path(value)


def load_settings(config_path: str, *, use_store: bool = True) -> Settings:
    defaults = default_settings()
    if not os.path.exists(config_path):
        return defaults

    with open(config_path, "rb") as handle:
        document = tomllib.load(handle)

    general = document.get("media_converterr", {})
    if not isinstance(general, dict):
        raise ConfigurationError("[media_converterr] must be a table")

    instances_value = document.get("instances")
    instances = defaults.instances if instances_value is None else parse_instances(instances_value)

    raw_unlinked = general.get("unlinked_folders", list(defaults.unlinked_folders))
    if not isinstance(raw_unlinked, list):
        raise ConfigurationError("unlinked_folders must be an array")

    raw_exclude = general.get("exclude", list(defaults.exclude))
    raw_extensions = general.get(
        "convertible_extensions", list(defaults.convertible_extensions)
    )
    if not isinstance(raw_exclude, list) or not isinstance(raw_extensions, list):
        raise ConfigurationError("exclude and convertible_extensions must be arrays")

    settings = Settings(
        database_path=_absolute_config_path(
            general.get("database", defaults.database_path), "database"
        ),
        source_database_path=_absolute_config_path(
            general.get("source_database", defaults.source_database_path),
            "source_database",
        ),
        work_dir=_absolute_config_path(
            general.get("work_dir", defaults.work_dir), "work_dir"
        ),
        lock_path=_absolute_config_path(
            general.get("lock", defaults.lock_path), "lock"
        ),
        log_dir=_absolute_config_path(
            general.get("log_dir", defaults.log_dir), "log_dir"
        ),
        exclude=tuple(str(item) for item in raw_exclude),
        convertible_extensions=tuple(
            str(item).lower().lstrip(".") for item in raw_extensions
        ),
        unlinked_folders=tuple(
            _absolute_config_path(item, "unlinked_folders item")
            for item in raw_unlinked
        ),
        instances=instances,
        poll_seconds=float(general.get("poll_seconds", defaults.poll_seconds)),
        settle_seconds=float(general.get("settle_seconds", defaults.settle_seconds)),
        callback_delay_seconds=float(
            general.get("callback_delay_seconds", defaults.callback_delay_seconds)
        ),
        retry_base_seconds=float(
            general.get("retry_base_seconds", defaults.retry_base_seconds)
        ),
        retry_max_seconds=float(
            general.get("retry_max_seconds", defaults.retry_max_seconds)
        ),
        max_conversion_attempts=int(
            general.get(
                "max_conversion_attempts", defaults.max_conversion_attempts
            )
        ),
        api_timeout_seconds=float(
            general.get("api_timeout_seconds", defaults.api_timeout_seconds)
        ),
        hook_spool_dir=_absolute_config_path(
            general.get("hook_spool_dir", defaults.hook_spool_dir),
            "hook_spool_dir",
        ),
    )
    jellyfin = document.get("jellyfin")
    if jellyfin is not None:
        settings = dataclasses.replace(settings, jellyfin=parse_jellyfin(jellyfin))
    if use_store:
        settings = apply_stored_connections(settings, settings_store.read(settings.database_path, "connections"))
        try:  # conversion policy saved from the web interface (module globals of the policy module)
            get_legacy_converter().apply_conversion_settings(settings_store.read(settings.database_path, "conversion"))
            get_legacy_converter().apply_capabilities(settings_store.read(settings.database_path, "capabilities"))
        except (ValueError, TypeError) as error:
            raise ConfigurationError(f"Saved conversion settings are invalid: {error}") from None
    if settings.max_conversion_attempts < 1:
        raise ConfigurationError("max_conversion_attempts must be at least 1")
    for name, value in (
        ("poll_seconds", settings.poll_seconds),
        ("settle_seconds", settings.settle_seconds),
        ("callback_delay_seconds", settings.callback_delay_seconds),
        ("retry_base_seconds", settings.retry_base_seconds),
        ("retry_max_seconds", settings.retry_max_seconds),
        ("api_timeout_seconds", settings.api_timeout_seconds),
    ):
        if value < 0:
            raise ConfigurationError(f"{name} cannot be negative")
    return settings


def setup_logging(settings: Settings, verbose: bool = False) -> logging.Logger:
    logger = logging.getLogger(APP_NAME)
    logger.handlers.clear()
    logger.setLevel(logging.DEBUG if verbose else logging.INFO)
    formatter = logging.Formatter("%(asctime)s %(levelname)s %(message)s")
    stderr_handler = logging.StreamHandler()
    stderr_handler.setFormatter(formatter)
    logger.addHandler(stderr_handler)

    for directory in (settings.log_dir, os.path.join(settings.work_dir, "logs")):
        try:
            os.makedirs(directory, exist_ok=True)
            file_handler = logging.handlers.RotatingFileHandler(
                os.path.join(directory, "media-converterr.log"),
                maxBytes=10 * 1024 * 1024,
                backupCount=5,
            )
            file_handler.setFormatter(formatter)
            logger.addHandler(file_handler)
            break
        except OSError:
            continue
    return logger


